-- Документы к описанию задачи (13.10.2026).
--
-- Слова Кирилла: «блок описание должен быть с возможностью редактировать и
-- дополнять, в том числе файлами. Так же при создании задачи в блок
-- описание добавь возможность добавлять файлы, документы, скрины и так
-- далее». Техзадание, макет, скриншот ошибки — часть того, ЧТО поручено, а
-- не реплика в обсуждении: в переписке они уезжают вверх, и через неделю
-- исполнитель ищет «тот скрин» пролистыванием.
--
-- Колонка на самой задаче, той же формы, что `task_participants.done_files`
-- (миграция 0039): [{path, name, size, type}], файлы — в той же закрытой
-- корзине `item-files`, права на которую решает первый сегмент пути (0020).
-- Пишет её синхронизация вместе с описанием: описание правит постановщик, и
-- это та же правка, что и текст.
--
-- `not null default '[]'` — потому что синхронизация пишет пачками, а
-- PostgREST в пачке не подставляет значения по умолчанию (см. CLAUDE.md):
-- строка без ключа получила бы NULL. taskToRow поэтому всегда шлёт массив.
alter table public.tasks add column if not exists desc_files jsonb not null default '[]'::jsonb;
