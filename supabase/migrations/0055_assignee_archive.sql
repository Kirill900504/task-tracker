-- Убрать человека из команды, не стирая того, что он делал (14.10.2026).
--
-- Слова Кирилла: «в разделе команда добавь функционал добавлять новых и
-- удалять не нужных людей». Удалять строку `assignees` нельзя: на неё
-- каскадом держатся участие во всех задачах и встречах («принял»,
-- «сделал» с комментарием, голоса), и однажды такой каскад уже стёр
-- Михаила Котова со всей его историей (см. useTrackerData, ветка людей).
--
-- Поэтому «удалить» — это пометка: человек уходит из «Команды», из всех
-- списков выбора и из разбора имён в боте, вход и мессенджер у него
-- отключаются, а строки участия остаются, и закрытые задачи по-прежнему
-- говорят, кто их делал. Строку без единого следа маршрут удаляет
-- по-настоящему — там терять нечего (опечатка, дубль).
--
-- Применяется ДО кода: выборки списка людей фильтруют по этой колонке и
-- без неё отвечают ошибкой.

alter table public.assignees add column if not exists archived_at timestamptz;

create index if not exists assignees_active_idx on public.assignees (user_id) where archived_at is null;
