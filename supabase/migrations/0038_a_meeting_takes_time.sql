-- Встреча занимает время, а не только точку на часах.
--
-- До сих пор у встречи было «когда начинается» и ничего о том, сколько
-- она идёт. Из-за этого нельзя было ответить на единственный вопрос,
-- который задают при назначении: свободен ли человек. Слова Кирилла
-- 20.09.2026: «чтобы другие участники работы видели, что условно на 12:00
-- у Есиной, Мамаковой и Макарова варианта выбрать встречу нету, потому
-- что у них уже запланирована встреча».
--
-- Тридцать минут по умолчанию: сетка выбора времени и так идёт получасом,
-- и все встречи, заведённые до сегодня, были назначены в этой сетке.
-- Значение ограничено двумя вариантами нарочно — «сколько угодно минут»
-- превращает выбор времени в поле ввода, а выбор из двух кнопок остаётся
-- одним нажатием.
alter table public.meetings
  add column if not exists duration_min int not null default 30
    check (duration_min in (30, 60));

-- Занятость спрашивают по дню: «кто свободен в этот четверг». Индекс по
-- паре «пространство + дата» — ровно тот запрос, который для этого идёт.
create index if not exists meetings_day_idx
  on public.meetings (user_id, date)
  where deleted_at is null;

comment on column public.meetings.duration_min is
  'Сколько минут занимает встреча: 30 или 60. Из этого считается занятость людей при выборе времени.';
