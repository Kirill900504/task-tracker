-- Сводка вместо ленты.
--
-- Слова Кирилла, сказанные над снимком собственной переписки с ботом: «если
-- таким сплошняком инфа будет переть, я офигею это всё читать и элементарно
-- не смогу нормально воспринимать». На снимке шесть сообщений подряд, каждое
-- про своё, каждое в две-три строки, и ни одно не связано с соседним. А
-- людей в трекере четырнадцать, и каждый из них за день нажимает «принял»,
-- «сделал», «не могу» и пишет в обсуждении.
--
-- Считать это мелочью нельзя: лента, которую перестают читать, перестаёт
-- читаться целиком — вместе с «не могу» и «просрочено», ради которых весь
-- трекер и затевался.
--
-- Поэтому всё, что адресовано ПОСТАНОВЩИКУ, больше не уходит по событию, а
-- копится здесь и выходит одним письмом, сгруппированным по смыслу: кто
-- принял, кто отчитался, кто не может, о чём писали. Кроном, который и так
-- ходит каждые несколько минут, — то есть задержка меньше той, за которую
-- человек успевает дойти до телефона.
--
-- Что НЕ копится и уходит сразу: всё, адресованное исполнителю. Задача,
-- возврат на доработку, решение по переносу, итог встречи — там ждут
-- ответа от него, и задержка стоит дороже порядка.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0030_one_message_instead_of_ten.sql

create table if not exists public.notification_queue (
  id uuid primary key default gen_random_uuid(),
  -- Пространство, которому принадлежит событие.
  user_id uuid not null references auth.users(id) on delete cascade,
  -- Кому адресовано. Владелец — это auth-пользователь; руководитель тоже,
  -- но пишут ему в чат его строки в списке людей (см. botDelivery).
  to_user uuid references auth.users(id) on delete cascade,
  -- Вид события: по нему строки группируются в письме.
  kind text not null,
  -- Название задачи или встречи, человек и его слова — тремя полями, а не
  -- одной готовой строкой: заголовок группы пишется при отправке, и
  -- склеенный заранее текст пришлось бы разбирать обратно.
  item text not null default '',
  who text not null default '',
  what text not null default '',
  created_at timestamptz not null default now(),
  sent_at timestamptz
);

-- Выборка всегда одна: неотправленное этого пространства, по порядку.
create index if not exists notification_queue_pending_idx
  on public.notification_queue (user_id, created_at)
  where sent_at is null;

alter table public.notification_queue enable row level security;

-- Читать и писать сюда может только служебный клиент: очередь наполняют
-- маршруты и вебхуки, а разбирает крон. Браузеру она не нужна ни для чего,
-- и политики поэтому нет вовсе — RLS без единой политики запрещает всё.
comment on table public.notification_queue is
  'Очередь уведомлений постановщику. Копится по событию, уходит одним письмом из cron/reminders — см. миграцию 0030.';
