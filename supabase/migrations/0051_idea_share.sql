-- «Отправить» и «Поделиться» — две разные передачи мысли.
--
-- Решение Кирилла 23.09.2026 (docs/next-ten.md, п. 12), сделано 08.10.2026:
-- «Отправить» — мысль уходит из списка автора, получатель обязан ответить
-- («В работу» / «Сохранить» / «Принял»); «Поделиться» — мысль остаётся у
-- автора как была и просто становится видна получателю в его списке,
-- ничего не подтверждается.
--
-- Колонка на той же строке рассылки, а не своя таблица: и то и другое —
-- «кому мысль передана», с той же видимостью (is_participant), тем же
-- «взял в работу» (converted_task_id) и тем же «закончил с ней» (seen_at —
-- у поделённой это значит «убрал у себя»). Вторая таблица о том же факте
-- разошлась бы с первой, как здесь расходилось уже трижды.
--
-- Все прежние строки — «отправить»: другой передачи до сегодняшнего дня
-- не было.
