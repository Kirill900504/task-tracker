-- Трекер сам сообщает, что сломался.
--
-- 19.09.2026 он дважды падал в белый экран — у Кирилла и, значит, у всех
-- четырнадцати, — и оба раза мы узнали об этом из его сообщения. Между
-- поломкой и сообщением прошло время, за которое он успел решить, что
-- сломалось всё; а между сообщением и починкой — ещё час, потому что
-- искать приходилось по описанию «вылетает эта ошибка на белом экране».
--
-- Ошибка, о которой не знает никто, кроме пострадавшего, — это не «редкий
-- случай», это отсутствующий орган чувств. Здесь он появляется: браузер
-- ловит падение и присылает строку, а владелец получает сообщение в
-- мессенджер.
--
-- Почему своя таблица, а не Sentry. Сторонний сборщик означает чужой
-- аккаунт, чужую панель и четыре экрана настроек в чужом интерфейсе —
-- ровно то, чего в этом проекте избегают (правило «две кнопки и пароль» в
-- CLAUDE.md). Плюс тексты ошибок содержат куски данных, и увозить их на
-- чужой сервер незачем, когда своя база уже есть.
--
-- Политик на вставку нет НАМЕРЕННО: пишет сюда только маршрут
-- /api/client-error служебным ключом. Иначе любой браузер мог бы залить
-- таблицу — а ошибка, которая повторяется в цикле (ровно так и падал
-- трекер сегодня), шлёт сотни строк в минуту.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0035_the_tracker_reports_its_own_crashes.sql

create table if not exists public.client_errors (
  id uuid primary key default gen_random_uuid(),
  -- Кто это видел. Пусто — значит упало до входа, на странице логина: такое
  -- тоже надо знать, поэтому колонка допускает null, в отличие от прочих
  -- пользовательских таблиц.
  user_id uuid references auth.users(id) on delete set null,
  -- Чьё пространство, чтобы было кому сказать.
  owner_id uuid references auth.users(id) on delete set null,
  message text not null,
  stack text,
  -- Где это случилось и на какой версии — без этого «белый экран» нельзя
  -- привязать ни к странице, ни к выкладке.
  url text,
  release text,
  -- Одна и та же поломка у четырнадцати человек — это одна поломка.
  -- Отпечаток режется из текста ошибки и служит для склейки и для того,
  -- чтобы владельцу не пришло четырнадцать одинаковых сообщений.
  fingerprint text not null,
  created_at timestamptz not null default now()
);

alter table public.client_errors enable row level security;

-- Чтения из браузера нет вовсе: это журнал для нас, а не экран для людей.
-- Служебный ключ политики обходит, и только он сюда и ходит.

create index if not exists client_errors_fingerprint_idx
  on public.client_errors (fingerprint, created_at desc);

create index if not exists client_errors_created_idx
  on public.client_errors (created_at desc);
