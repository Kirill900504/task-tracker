-- «Отложить до…» у постановщика (п.2.6 предложений, 07.10.2026, «делай»).
--
-- Задача на приёмке, которую примут только после разговора в четверг, или
-- просроченная, о которой уже договорились, висит на доске и каждый день
-- требует внимания, которого ей сейчас не нужно. Постановщик откладывает
-- её до дня: до этого дня она уходит с ЕГО доски (у исполнителей всё как
-- было — их работа не откладывается), а в этот день бот напоминает о ней.
--
-- Колонка на самой задаче, а не своя таблица: откладывает только автор, и
-- пишет её синхронизация, как и срок. Пусто или прошлое — не отложена.
alter table public.tasks add column if not exists snoozed_until date;
