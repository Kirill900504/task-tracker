-- Отвечать можно только через маршрут — теперь и по правилам базы.
--
-- Правила «отчёт без комментария не отчёт», «отказ без причины не отказ»,
-- «отчитались все — задача уходит на приёмку» и «постановщик должен об этом
-- узнать» живут в /api/workspace/report. Маршрут пишет служебным клиентом,
-- который правила доступа обходит, — и это правильно: проверки уже сделаны
-- до записи.
--
-- Но рядом с ним стояли три политики, разрешавшие руководителю писать в те
-- же строки напрямую из браузера: отметить отчёт, проголосовать, пометить
-- мысль. Интерфейс так никогда не делал — все ответы идут маршрутом, — а
-- база позволяла. То есть отчёт без единого слова, отказ без причины и
-- задача, которая так и не ушла на приёмку, отделялись от боевой базы одной
-- строчкой в консоли браузера.
--
-- Аудит 15.09.2026 назвал это «правила базы разрешают больше, чем разрешают
-- маршруты». Здесь это и закрывается: остаётся ровно один путь, тот самый,
-- в котором живут проверки.
--
-- Что НЕ трогается: чтение. Руководитель по-прежнему видит свои строки
-- (политики *_visible), и владелец по-прежнему пишет свои (*_owner_write) —
-- назначение, роли, состав встречи.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0023_answers_only_through_the_route.sql

drop policy if exists "task_participants_report_self" on public.task_participants;
drop policy if exists "meeting_participants_vote_self" on public.meeting_participants;
drop policy if exists "idea_recipients_mark_self" on public.idea_recipients;
