-- Приёмка по выбору (14.10.2026).
--
-- Предложение 2 из разбора 13.10.2026, одобренное Кириллом: «приёмка по
-- выбору, а не всегда (Битрикс24: „проконтролировать задачу после
-- завершения“ — галочка при постановке). Для мелких поручений („позвони в
-- банк“) отчёт исполнителя закрывает задачу сам, без вашего нажатия».
--
-- По умолчанию приёмка нужна — так трекер работал всегда, и старые задачи
-- ведут себя как прежде. Выключает её постановщик в форме новой задачи;
-- закрывает такую задачу сервер, когда отчитались все исполнители
-- (colleagueReplies.closeIfEveryoneReported) — тем же applyReview, что и
-- обычная приёмка, чтобы хроника, повтор и сообщения не разошлись.
-- Отказ кого-то из исполнителей задачу НЕ закрывает: это вопрос, который
-- решает постановщик, а не повод считать работу сделанной.
--
-- Колонку пишет синхронизация (taskToRow) — всегда, потому что пачка
-- PostgREST не подставляет значения по умолчанию (CLAUDE.md).
alter table public.tasks add column if not exists needs_review boolean not null default true;
