-- Встречу можно предложить, а не только назначить.
--
-- У встречи было три состояния: запланирована, прошла успешно, прошла без
-- результата. Назначить — значит занять чужое время, и у владельца такое
-- право есть по определению. У руководителя, зовущего двух других, его нет:
-- он предлагает.
--
-- До сих пор разницы не было никакой, и любая встреча, созданная кем
-- угодно, сразу попадала в календарь и начинала слать напоминания. То есть
-- четырнадцать человек получили возможность ставить друг другу встречи в
-- обязательном порядке — ровно то, чего не стал бы делать ни один из них,
-- будь у него выбор.
--
-- Четвёртое состояние, а не отдельная таблица и не флаг: «предложена» — это
-- то же самое место в жизни встречи, что «запланирована», просто раньше
-- него. Флаг рядом со статусом дал бы две правды об одном факте, и они
-- разошлись бы — в этом проекте так было трижды.
--
-- Что из этого следует само, без единой строчки кода: напоминания и
-- календарь спрашивают `status = 'planned'` и предложенную встречу не
-- увидят. Это и есть смысл состояния — она существует, её видно, по ней
-- можно ответить, но время она ещё не занимает.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0034_a_meeting_can_be_proposed.sql

alter table public.meetings
  drop constraint if exists meetings_status_check;

alter table public.meetings
  add constraint meetings_status_check
  check (status in ('proposed', 'planned', 'success', 'no_result'));

comment on column public.meetings.status is
  'proposed: предложена, время не занимает. planned: назначена. success/no_result: прошла (миграция 0034).';
