-- Повтор «в рабочий день» (15.10.2026).
--
-- Предложение Михаила Котова, одобренное Кириллом: «есть повторяющаяся
-- операция, ставишь на 1-е число, и в какой-то месяц выпадет на сб. или вс.
-- Так вот в задаче галка — рабочие дни, и задача встанет на 2-е число, если
-- 1-е это воскресенье». Касается ежемесячного и ежегодного повтора: у
-- недельного дни выбирают руками, а ежедневный по будням уже есть.
--
-- Сам перенос считает код (lib/recurShift) — и в браузере, и в кроне, —
-- база хранит только выбор. По умолчанию выключено: старые задачи ведут
-- себя как прежде.
--
-- Колонку пишет синхронизация (taskToRow) — всегда, потому что пачка
-- PostgREST не подставляет значения по умолчанию (CLAUDE.md).
alter table public.tasks add column if not exists recur_workday boolean not null default false;
