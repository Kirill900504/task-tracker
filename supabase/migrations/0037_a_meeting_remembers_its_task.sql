-- Встреча, выросшая из задачи, помнит эту задачу.
--
-- Задачу нельзя «превратить» во встречу: по задаче собираются, а сама она
-- никуда не девается. Связь между ними до сих пор жила строкой в
-- обсуждении обеих сторон (см. lib/itemLink) — человеку этого хватало,
-- машине нет: чтобы дописать ИТОГ встречи в ту задачу, ради которой
-- собирались, надо знать её идентификатор, а не читать текст реплики.
--
-- Слова Кирилла 19.09.2026 о том, чего он хочет от связки: «перекидывание
-- задачи во встречу на финальном этапе, автоматическое закрытие встреч с
-- комментарием ИТОГа после проведения». Вторая половина этой фразы и
-- упиралась в отсутствие колонки.
--
-- Строки в обсуждении при этом остаются: их читают, и читать их удобнее,
-- чем колонку. Это не вторая правда об одном факте — это подпись под ней.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0037_a_meeting_remembers_its_task.sql

alter table public.meetings
  add column if not exists from_task_id text references public.tasks(id) on delete set null;

create index if not exists meetings_from_task_idx on public.meetings (from_task_id) where from_task_id is not null;

comment on column public.meetings.from_task_id is
  'Задача, ради которой собрались. Итог такой встречи дописывается в её обсуждение (миграция 0037).';
