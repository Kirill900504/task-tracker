-- Номер задачи и её идентификатор — в строке очереди (14.10.2026).
--
-- Слова Кирилла над снимком сводки: «в мессенджеры обязательно надо
-- добавить номера задач, для ориентира и убери дублирование информации».
-- На снимке одна и та же задача с названием в десять строк стояла в
-- сводке дважды — в «Не могут выполнить» и в «Написали в обсуждении», — и
-- понять, что это одна задача, можно было только перечитав оба абзаца.
--
-- Номер (миграция 0045) короче названия и одинаков в трекере и в боте:
-- по нему задачу и называют. Идентификатор нужен сборщику сводки, чтобы
-- склеить события ОДНОГО человека по ОДНОЙ задаче в одну строку и чтобы
-- проверить «уже закрыта» по самой задаче, а не по совпадению названий
-- (у двух задач «Отчёт» одно название и разная судьба).
--
-- Обе колонки необязательны: строки, положенные до этой миграции, и
-- события без задачи (мысль, встреча без номера) живут как жили.
--
-- Применяется ДО кода: код кладёт в очередь новые колонки, и без них
-- вставка откажет — событие уйдёт отдельным сообщением по старой дороге
-- (queueNotice → false), то есть ровно той лентой, от которой очередь
-- спасает.
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0054_notice_item_ref.sql

