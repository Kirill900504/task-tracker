-- Зависимость «эта задача ждёт ту» (14.10.2026).
--
-- Предложение 3 из разбора 13.10.2026, одобренное Кириллом: «зависимости
-- „Б ждёт А“ (Asana, Notion): задача Б не уходит в работу и не краснеет,
-- пока не закрыта А». Смету не согласовать, пока нет прайса; без этой
-- связи исполнитель сметы видит на доске задачу, которую не может начать,
-- и постановщик спрашивает с него то, что от него не зависит.
--
-- Одна колонка на задаче, а не таблица связей: задача ждёт одну другую —
-- это и есть девять случаев из десяти, а граф зависимостей — та самая
-- «вложенность», которую трекер нарочно не делает (docs/next-ten.md).
-- Пишет её постановщик через синхронизацию, как срок.
--
-- `on delete set null`: удалённая задача никого не держит. Мягкое удаление
-- (deleted_at) строку не удаляет — его учитывает код, который считает
-- «ждёт» только открытую, неудалённую задачу.
alter table public.tasks add column if not exists blocked_by text references public.tasks(id) on delete set null;
create index if not exists tasks_blocked_by_idx on public.tasks (blocked_by) where blocked_by is not null;
