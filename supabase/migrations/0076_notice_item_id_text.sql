-- Идентификатор дела в очереди уведомлений — текст, как у самих дел.
--
-- 0054 объявила notification_queue.item_id как uuid, а id задач, встреч и
-- мыслей — текст вида «tmh3k…» (0002_fix_id_type). Каждая вставка события
-- с делом отвечала 22P02, queueNotice возвращал false, и событие уходило
-- по запасной дороге — отдельным сообщением сразу. То есть с 14.10.2026
-- сводки постановщику не было вовсе: «выполнил…» и через минуту слова
-- исполнителя приходили двумя сообщениями (№154, 30.10.2026), хотя
-- foldNotices склеивает их в одну строку.
--
-- Строк с item_id в таблице нет (ни одна вставка с ним не прошла), так что
-- смена типа ничего не теряет. Код до этой миграции тоже работает:
-- queueNotice при 22P02 повторяет вставку без item_id.
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0076_notice_item_id_text.sql

alter table public.notification_queue alter column item_id type text using item_id::text;
