-- «По понедельникам и четвергам» и «по будням».
--
-- Недельный повтор знал ровно один день: `recur_weekday`, число от нуля до
-- шести. А половина повторяющихся поручений в жизни звучит иначе — «каждый
-- понедельник и четверг», «по будням», «в начале и в середине недели». Всё
-- это до сих пор заводилось двумя разными задачами с одинаковым названием,
-- и дальше они жили каждая своей жизнью: одну закрыли, вторую забыли.
--
-- Массив, а не вторая колонка и не отдельный вид повтора: «по будням» — это
-- и есть пять дней недели, а не новое понятие. Новый вид повтора пришлось
-- бы учесть в каждом месте, которое спрашивает «какой сегодня день», и в
-- каждом ответ был бы одинаков.
--
-- Старая колонка остаётся и продолжает читаться: у задач, заведённых до
-- этой миграции, массив пуст, и «по средам» должно работать ровно как
-- работало. Переносить их незачем — правило «сначала массив, если пуст, то
-- колонка» короче любого переноса и не может ошибиться на данных, которых
-- ещё не видело.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0032_more_than_one_weekday.sql

alter table public.tasks
  add column if not exists recur_weekdays smallint[] not null default '{}';

comment on column public.tasks.recur_weekdays is
  'Дни недели недельного повтора, 0=вс…6=сб. Пусто — читается старый recur_weekday (миграция 0032).';
