-- Раздел «Общие» убран.
--
-- Он появился в миграции 0010 первым в списке — и за всё время не собрал ни
-- одной задачи. Это ровно то, чем он был: не раздел работы, а слово «прочее»
-- в начале списка, в который надо попасть, прежде чем выбрать настоящий
-- раздел. Кирилл попросил его убрать, и убрать его стоит там же, где он
-- заведён, — миграцией: иначе свежая база (и `npm run test:schema`) будет
-- отличаться от боевой ровно на этот раздел.
--
-- Задачи, если они вдруг в нём окажутся, раздел не теряют вместе с собой:
-- внешний ключ у tasks.section_id стоит `on delete set null`, то есть они
-- просто станут «без раздела». Здесь это записано явно, чтобы намерение
-- читалось без похода в 0010.

update public.tasks set section_id = null where section_id = 'sec_general';
delete from public.sections where id = 'sec_general';
