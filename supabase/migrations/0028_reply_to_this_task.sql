-- Ответ из мессенджера адресуется задаче, а не угадывается.
--
-- До сих пор текст, написанный коллегой в бот, уходил в обсуждение «самой
-- свежей открытой задачи» — код честно угадывал и честно называл, куда
-- записал. У человека с одной задачей это работало безупречно. У человека
-- с пятью реплика уезжает не туда, и это не сообщение в чате, которое
-- можно переписать: это запись в истории задачи, которую через месяц
-- читают как доказательство того, что было сказано.
--
-- Поэтому под каждой задачей появляется кнопка «Ответить», а её нажатие
-- нужно где-то запомнить до следующего сообщения. Место то же самое, что
-- у владельца: у него это `pending_context` в таблице аккаунтов, здесь —
-- три колонки на строке человека, потому что коллега не аккаунт и своей
-- таблицы у него нет.
--
-- Почему со сроком годности: незакрытое намерение хуже, чем его
-- отсутствие. Человек нажал «Ответить», отвлёкся на два часа и написал
-- совсем о другом — попасть это должно туда же, куда попало бы без
-- нажатия, а не в задачу, о которой он уже забыл. Два часа — та же пауза,
-- по которой обсуждение считает разговор новым (см. colleagueReplies).
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0028_reply_to_this_task.sql

alter table public.assignees
  add column if not exists pending_reply_kind text
    check (pending_reply_kind in ('task', 'meeting')),
  add column if not exists pending_reply_id text,
  add column if not exists pending_reply_at timestamptz;

comment on column public.assignees.pending_reply_id is
  'Куда направлен следующий текст от этого человека — итем, под которым он нажал «Ответить». Живёт два часа, см. миграцию 0028.';

-- Правами на колонки это НЕ закрывается, в отличие от токена в
-- `bot_settings`, и вот почему. Тот приём — `revoke all` плюс `grant
-- select` перечислением — требует назвать поимённо все остальные колонки
-- таблицы, и следующая добавленная колонка окажется невидимой, пока
-- кто-нибудь не вспомнит дописать её в этот список. Цена ошибки здесь
-- несопоставима с выигрышем: в этих полях лежит id задачи, которую человек
-- и так вправе видеть, а не секрет. Пишет их только служебный клиент из
-- вебхука.
