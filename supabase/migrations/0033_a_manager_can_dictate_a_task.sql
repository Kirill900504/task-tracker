-- Руководитель диктует задачу в бот, как это делает Кирилл.
--
-- Быстрый ввод («поручи Игорю смету к пятнице») работал только у владельца:
-- у него есть строка в таблице аккаунтов, где и лежит память бота — что
-- спросили, что ждёт подтверждения. У коллеги такой строки нет и быть не
-- должно: он не аккаунт, он человек, которому пишут.
--
-- А руководитель теперь ставит задачи наравне с владельцем — и, чтобы
-- поставить одну, ему надо открыть трекер. Для человека, который весь день
-- за рулём и в мессенджере, это ровно та преграда, из-за которой поручение
-- не превращается в задачу.
--
-- Память нужна ровно одна: разобранная фраза, ждущая «да». Модель не
-- назначает людей молча — это правило проекта, и оно дороже одного лишнего
-- шага: список показывается и создаётся только по подтверждению.
--
-- Колонка та же по смыслу, что `pending_action` у аккаунтов, и намеренно
-- так же названа: два имени для одного и того же — это место, где однажды
-- поправят одно, а второе забудут.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0033_a_manager_can_dictate_a_task.sql

alter table public.assignees
  add column if not exists pending_action jsonb;

comment on column public.assignees.pending_action is
  'Разобранная фраза, ждущая «да» от этого человека. Пишет и читает только вебхук (миграция 0033).';
