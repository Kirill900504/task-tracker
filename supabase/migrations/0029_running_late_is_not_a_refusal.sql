-- «Опоздаю» — это не «не приду».
--
-- У встречи было два ответа: буду и не смогу. Человек, который задержится
-- на двадцать минут, обязан выбрать один из них, и оба неправда: «буду»
-- молчит о том, что начала он не застанет, а «не смогу» вычёркивает его из
-- встречи целиком и требует причины, которой нет. На практике это значит,
-- что он жмёт «буду» и просто опаздывает — то есть организатор узнаёт о
-- задержке в момент задержки.
--
-- Почему колонка, а не третье значение `response`. Для подсчёта «кто
-- придёт» опоздавший — это пришедший: встречу из-за него не переносят и
-- кворум он не ломает. Третье значение пришлось бы учесть в каждом месте,
-- которое сегодня спрашивает «yes или no» — в подсчёте голосов, в карточке,
-- в напоминаниях, в сводках, — и в каждом из них ответ был бы «считать как
-- yes». Колонка говорит ровно то, что добавилось: придёт, но позже.
--
-- Применяется так:
--   node --env-file=.env.local scripts/run-migration.mjs \
--     supabase/migrations/0029_running_late_is_not_a_refusal.sql

alter table public.meeting_participants
  add column if not exists late boolean not null default false;

comment on column public.meeting_participants.late is
  'Придёт, но опоздает. Для подсчёта это обычный yes — см. миграцию 0029.';
