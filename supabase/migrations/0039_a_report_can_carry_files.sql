-- Отчёт может нести документы.
--
-- Слова Кирилла 21.09.2026 про карточку задачи: «далее нужно для заполнения
-- поле Результат с датой и временем проведения и возможностью прикрепления
-- документа. Чтобы постановщик задачи на приёмке мог прочесть данные по
-- результату и принять решение».
--
-- Дата и время у отчёта уже были (`done_at`), текст тоже (`done_comment`), а
-- документа не было вовсе: приложить файл можно было только в обсуждение,
-- то есть В ДРУГОМ МЕСТЕ, чем сам результат. На приёмке это означает, что
-- акт, фотографию или выгрузку надо искать в переписке, пролистывая её
-- вверх, — а приёмка и есть тот единственный момент, когда этот файл
-- нужен.
--
-- Колонка, а не отдельная таблица: файл здесь — часть одного ответа одного
-- человека, живёт и умирает вместе с его строкой (возврат на доработку
-- стирает отчёт целиком — см. правило про хронику в CLAUDE.md), и
-- спрашивать его отдельным запросом было бы третьим обращением ради
-- двух строк. Форма та же, что у вложений обсуждения
-- (`item_comments.attachments`): массив {path, name, size, type}, а сами
-- файлы лежат в той же закрытой корзине `item-files`, где у них нет
-- постоянного адреса — только подписанная ссылка на час.
--
-- Писать эту колонку может ТОЛЬКО маршрут служебным ключом
-- (/api/workspace/report): отчёт идёт через маршрут целиком, потому что
-- вместе с ним проверяется обязательный комментарий, двигается приёмка и
-- уходит сообщение постановщику. Из браузера сюда не пишут — политики на
-- запись в task_participants у исполнителя нет и не было.
alter table public.task_participants
  add column if not exists done_files jsonb not null default '[]'::jsonb;

comment on column public.task_participants.done_files is
  'Документы к отчёту: [{path,name,size,type}] в корзине item-files. Пишет только /api/workspace/report.';
