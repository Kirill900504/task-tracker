import { join } from "node:path";

// Где лежит одноразовый тестовый пользователь этого прогона.
//
// Раньше имя было одно на всю рабочую копию — `.e2e-user.json`, — и это
// работало ровно до тех пор, пока прогон был один. Кирилл держит два чата
// одновременно, то есть в одном каталоге живут две сессии: вторая заводит
// своего пользователя поверх файла первой, а её teardown этот файл сносит
// и УДАЛЯЕТ аккаунт — посреди чужого прогона. Выглядит это как каскад
// падений на ровном месте: половина тестов валится с «ENOENT
// .e2e-user.json», остальные — на первом же действии после входа, потому
// что аккаунта, под которым они вошли, больше нет. Так сорвались два
// прогона подряд 20.09.2026, и оба раза первые минуты ушли на поиск
// регрессии, которой не было.
//
// Поэтому имя файла своё у каждого прогона. Идентификатор ставит
// global-setup (`E2E_RUN`) — Playwright запускает воркеры уже после него и
// передаёт им своё окружение, так что все читают то же имя, которое
// записал setup. Если переменной нет (кто-то позвал spec напрямую),
// остаётся прежнее имя: пусть лучше сработает старый путь, чем тест
// упадёт на отсутствующем файле.
export function userFilePath(): string {
  const run = process.env.E2E_RUN;
  return join(__dirname, run ? `.e2e-user-${run}.json` : ".e2e-user.json");
}
