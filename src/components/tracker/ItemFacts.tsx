"use client";

import type { ReactNode } from "react";

// Главное о задаче или встрече — одной короткой таблицей.
//
// Слова Кирилла 21.09.2026 про карточку задачи: «требуется компактное окно
// с основной информацией… кто постановщик → напротив дата постановки
// задачи, кто исполнитель → напротив крайний срок выполнения… (ТУТ ПРОШУ
// ВНЕДРИТЬ ПОНЯТНУЮ КОМПАКТНУЮ И УДОБНУЮ ДЛЯ ВОСПРИЯТИЯ ФОРМУ ОСНОВНЫХ
// ДАННЫХ ПО ЗАДАЧЕ)». И тем же днём про встречу: «окно созданной встречи
// должно быть однотипным с окном созданной задачи».
//
// Отсюда форма: пары «кто» и «когда» в одной строке — они и читаются
// вместе («Игорь — до пятницы», «собрал Макаров — назначил во вторник»), а
// порознь заставляют прыгать глазами по столбцу из шести строк. Список
// людей занимает строку целиком: имён бывает пять, и делить их пополам
// нечем.
//
// Один компонент на оба окна — не экономия: «однотипное» у Кирилла
// означает, что ключевая информация лежит на ОДНОМ И ТОМ ЖЕ месте, а две
// копии этой разметки разъедутся так же, как разъезжались две копии всего
// остального в этом проекте.

export type Fact = {
  label: string;
  // Готовая разметка, а не строка: значением бывает список людей с
  // пометками, дата с признаком просрочки, «—» там, где не заполнено.
  value: ReactNode;
  // Мягче обычного, когда сказать по делу нечего («не назначен»).
  muted?: boolean;
};

export type FactRow =
  | { left: Fact; right?: Fact }
  // Во всю ширину: списки людей и всё, что не делится пополам.
  | { wide: Fact };

export default function ItemFacts({
  rows,
  id,
  // Бейдж в углу блока — стадия задачи («в работе», «на приёмке»…).
  //
  // Слова Кирилла 22.09.2026: перенести пилюлю статуса из отдельного
  // блока «Кто на задаче» сюда, в верхнюю сводку, «в такой же аккуратной
  // форме». Форма и есть та же самая: это тот же класс tp-stage, что
  // раньше стоял в TaskParticipants.tsx, просто теперь в другом месте.
  badge,
}: {
  rows: FactRow[];
  id?: string;
  badge?: ReactNode;
}) {
  // Бейдж стадии — в правом верхнем углу, на одной строке с
  // «Постановщиком» и «Датой постановки». Слова Кирилла 24.09.2026:
  // статус «должен быть в правом верхнем углу вровень со строкой, где
  // указан постановщик и дата постановки… целью тут является убрать
  // лишний отступ, который образуется за счёт того, что статус отдельной
  // строкой показывается». Две прежние попытки — строкой НАД сводкой и
  // строкой ПОД ней — обе тратили на пилюлю целую строку. Теперь она
  // делит ячейку с датой (.fact-pair): поместилась — стоит справа, нет —
  // переносится под дату, но на неё не наезжает.
  const badgeRow = badge ? rows.findIndex((r) => !("wide" in r)) : -1;
  return (
    <div className="facts" id={id}>
      {rows.map((row, i) =>
        "wide" in row ? (
          <div className="facts-row wide" key={i}>
            <FactCell fact={row.wide} />
          </div>
        ) : i === badgeRow ? (
          <div className="facts-row has-badge" key={i}>
            <FactCell fact={row.left} />
            <span className="fact-pair">
              {row.right ? <FactCell fact={row.right} /> : <span className="fact" />}
              <span className="facts-badge">{badge}</span>
            </span>
          </div>
        ) : (
          <div className="facts-row" key={i}>
            <FactCell fact={row.left} />
            {row.right ? <FactCell fact={row.right} /> : <span className="fact" />}
          </div>
        ),
      )}
      {/* Строк без пары не бывает у задачи, но компонент общий: если
          ставить пилюлю некуда, она остаётся последней строкой, как раньше. */}
      {badge && badgeRow < 0 && <div className="facts-badge-row">{badge}</div>}
    </div>
  );
}

function FactCell({ fact }: { fact: Fact }) {
  return (
    <span className="fact">
      <span className="fact-label">{fact.label}</span>
      <span className={"fact-value" + (fact.muted ? " muted" : "")}>{fact.value}</span>
    </span>
  );
}
