"use client";

// Три колонки, и они не двигаются.
//
// Здесь был конструктор: панели переставлялись мышью, порядок хранился у
// человека в настройках, пустая зона умела принимать блок обратно. Кирилл
// закрыл эту тему одной фразой 19.09.2026: «первым делом убираем
// возможность переносить блоки, они всё же должны быть статичны».
//
// Он прав, и причина видна как раз тогда, когда трекером пользуется не
// один человек. Раскладка — это не вкус, а место, о котором договорились:
// «календарь слева, задачи посередине» должно быть правдой для всех
// четырнадцати, иначе объяснить что-либо по телефону становится нельзя.
// А цена подвижности платилась каждый день: случайное движение мышью по
// ручке уносило панель, и вернуть её было отдельным делом.
//
// Что осталось от подвижного: перетаскивание САМОЙ РАБОТЫ — карточек,
// мыслей, встреч (см. dnd/TrackerDnd). Оно и было тем, ради чего всё
// затевалось.
import type { ReactElement } from "react";

export default function DashboardLayout({ panels }: { panels: Record<string, ReactElement> }) {
  // Порядок написан здесь и только здесь. Слева — «когда» (календарь и
  // встречи), в середине — «что» (доска задач), справа — «о чём» (мысли).
  // Панель, которой нет, просто не рисуется: так раскладка переживает
  // удаление любой из них без отдельной проверки на каждую — «Загрузка»
  // ушла отсюда в окно под кнопкой над доской именно так.
  const zones: Record<"left" | "center" | "right", string[]> = {
    left: ["calPanel", "meetingsPanel"],
    center: ["mainCol"],
    right: ["ideasPanel"],
  };

  return (
    <div className="layout" id="layoutGrid">
      {(["left", "center", "right"] as const).map((zone) => (
        <div key={zone} id={"zone" + zone[0].toUpperCase() + zone.slice(1)} className="dash-zone" data-zone={zone}>
          {zones[zone]
            .filter((id) => panels[id])
            .map((id) => (
              <div key={id} className="dash-slot" data-panel-slot={id}>
                {panels[id]}
              </div>
            ))}
        </div>
      ))}
    </div>
  );
}
