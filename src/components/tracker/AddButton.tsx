"use client";

// «+» слева от микрофона — у полей, где он делает СВОЁ дело: мысль, пункт
// повестки, быстрый ввод, итог встречи, правка описания и мысли.
// 21.10.2026, его слова: «слева от микрофона такую же фирменную кнопку „+“…
// везде слева надо воткнуть». Делает ровно то же, что Enter в этом поле, —
// третий, явный способ, а не новое действие; на телефоне Enter в
// однострочном поле не всегда под рукой, и кнопка там нужнее всего.
//
// Сперва поля ПРАВКИ были оставлены без «+» — «рядом есть „Готово“». Это
// было решение за Кирилла вопреки его «везде», и он его отменил тем же
// днём. В поле правки «+» записывает набранное (итог встречи — без
// исхода, исход по-прежнему кнопками).
//
// Где «+» НЕТ. Строка чата: рядом с микрофоном уже стоит «Отправить». И
// все поля форм НОВОЙ задачи и НОВОЙ встречи — название и описание: у поля
// там нет своей записи, «+» заводил задачу или встречу целиком, то есть
// повторял «Создать» внизу формы, а читался как «сохранить это поле».
// Кнопка у поля обязана делать то, что обещает её место (21.10.2026, его
// слова: «либо сохраняться описание должно, либо кнопка плюса лишняя… ну
// то же самое в названии задачи получается»).
import Icon from "./Icon";

export default function AddButton({
  onClick,
  disabled,
  title,
  id,
  type = "button",
  className = "",
}: {
  onClick?: () => void;
  disabled?: boolean;
  title: string;
  id?: string;
  // В форме быстрого ввода кнопка — её submit, чтобы путь был один с Enter.
  type?: "button" | "submit";
  className?: string;
}) {
  return (
    <button
      type={type}
      id={id}
      className={"field-mic-btn field-add-btn" + (className ? " " + className : "")}
      title={title}
      aria-label={title}
      disabled={disabled}
      onClick={onClick}
    >
      <Icon name="plus" size={16} />
    </button>
  );
}
