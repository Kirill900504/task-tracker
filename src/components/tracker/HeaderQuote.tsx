"use client";

import { useLayoutEffect, useRef, useState } from "react";

// Цитата в шапке — всегда одна строка, и всегда читаемая.
//
// Раньше её размер задавался в `vw` и подбирался «на глаз»: на широком
// экране строка стояла одна, а на ноутбуке 1366 приходила в тот же средний
// столбец шапки, места в котором вдвое меньше, и разваливалась на две-три
// строки. Догадаться о ширине этого столбца из `vw` нельзя в принципе:
// слева бренд, справа кнопки, которых бывает от пяти до девяти, и они ещё
// и переносятся. Единственный, кто знает ширину, — браузер, поэтому она
// измеряется, а не вычисляется.
//
// Одного замера, однако, мало, и это выяснилось на живом экране: у окна
// шириной 1900 кнопок в шапке набралось девять, среднему столбцу осталась
// треть, и кегль честно уехал к десяти пикселям. Формально «одна строка»,
// по сути — нечитаемая полоска мелких букв, которую Кирилл назвал
// «сжалась»; цитата ему дорога, и показывать её так — хуже, чем не
// показывать. Поэтому выбор теперь из двух мест, а не из одного кегля:
//
//   в строке с кнопками — пока остаётся достойный кегль (COMFORT_SIZE);
//   своей строкой во всю ширину шапки — как только перестаёт.
//
// Во всю ширину места втрое больше, и там цитата почти всегда набирается
// максимальным кеглем. Лишний ряд стоит недорого именно потому, что
// занимает его строка текста, а не заголовок, называющий очевидное.
//
// Приём точный, а не итеративный: ширина текста растёт ровно
// пропорционально кеглю, поэтому нужный кегль получается за один шаг —
// текущий, умноженный на отношение «сколько есть» к «сколько нужно».
// Обе ширины — и столбца, и всей шапки — считаются в КАЖДОМ замере, из
// размеров соседей, а не из текущего режима: решение, зависящее от
// собственного результата, и есть определение дребезга.

const QUOTE_HEAD = "Есть десятилетия, за которые ничего не случается, ";
const QUOTE_TAIL = "и есть недели, за которые случаются десятилетия.";

// Границы кегля. Верхняя — прежний размер строки: цитата не должна
// перерастать заголовок рядом с ней. Нижняя — та, ниже которой читать уже
// нечего; вместо нечитаемой строки цитата убирается совсем.
const MAX_SIZE = 19;
const MIN_SIZE = 12;

// Кегль, ниже которого цитате не место в одном ряду с кнопками: 15 — это
// размер подписи, а не фразы во всю шапку. Ровно здесь она уходит на
// собственную строку, где ей хватает места на MAX_SIZE.
const COMFORT_SIZE = 15;

// Возврат в ряд требует запаса: без него ширина, попавшая точно в COMFORT,
// переключала бы режим туда-обратно на каждый пиксель окна. Запас мал
// намеренно: чем он шире, тем заметнее разница между «пришли слева» и
// «пришли справа» — одна и та же шапка выглядела бы по-разному в
// зависимости от того, сужали окно или расширяли.
const RETURN_MARGIN = 0.5;

export default function HeaderQuote() {
  const boxRef = useRef<HTMLDivElement | null>(null);
  const lineRef = useRef<HTMLSpanElement | null>(null);
  const [size, setSize] = useState(MAX_SIZE);
  const [ownRow, setOwnRow] = useState(false);
  const [fits, setFits] = useState(true);

  useLayoutEffect(() => {
    const box = boxRef.current;
    const line = lineRef.current;
    if (!box || !line) return;

    function measure() {
      if (!box || !line) return;
      const row = box.parentElement;
      if (!row) return;

      // Ширина строки при кегле в один пиксель: единственная величина, из
      // которой выводится всё остальное. Меряется сама строка — inline-block
      // в nowrap, то есть ширина по тексту, «сколько нужно». Блоком её
      // мерить нельзя: блок растянут по контейнеру и вернул бы «сколько
      // есть», отчего цитата навсегда застревала бы на своей строке.
      const naturalPerPx = line.getBoundingClientRect().width / size;
      if (!naturalPerPx) return;

      const gap = parseFloat(getComputedStyle(row).columnGap) || 0;
      const neighbours = Array.from(row.children).filter((el) => el !== box);
      const taken = neighbours.reduce((sum, el) => sum + el.getBoundingClientRect().width, 0);

      // Два места, два кегля. Промежутков вычитается по числу соседей, а не
      // по числу настоящих зазоров: лишний десяток пикселей запаса дешевле
      // строки, обрезанной на последней букве.
      const inlineWidth = row.clientWidth - taken - gap * neighbours.length;
      const fullWidth = row.clientWidth;
      if (fullWidth <= 0) return;

      const inlineSize = (inlineWidth - 1) / naturalPerPx;
      const fullSize = (fullWidth - 1) / naturalPerPx;

      // В ряду — пока кегль достойный; вернуться в ряд можно только с
      // запасом, уйти из него — сразу.
      const staysInline = ownRow ? inlineSize >= COMFORT_SIZE + RETURN_MARGIN : inlineSize >= COMFORT_SIZE;
      const wanted = staysInline ? inlineSize : fullSize;

      if (staysInline === ownRow) setOwnRow(!staysInline);
      setFits(wanted >= MIN_SIZE);

      const next = Math.min(MAX_SIZE, Math.max(MIN_SIZE, wanted));
      // Порог против дребезга: без него округление кегля до субпикселя
      // заставляет замер и отрисовку гоняться друг за другом.
      //
      // Но порог не действует, когда строка НЕ ВЛЕЗАЕТ: десятая доля кегля —
      // это пять пикселей ширины, и на 1100 строка ровно так и торчала за
      // край, обрезанная на последнем слове, — разница в кегле была меньше
      // порога, и замер считал, что всё в порядке. Обрезанная фраза это не
      // дребезг, её видно.
      //
      // Против порога действует только УМЕНЬШЕНИЕ: шрифт растёт не строго
      // линейно (хинтинг), и разрешённая в обе стороны поправка на сотые
      // доли кегля гоняла бы замер по кругу. Уменьшение сходится всегда.
      const available = staysInline ? inlineWidth : fullWidth;
      const overflows = line.getBoundingClientRect().width > available + 0.5;
      if ((overflows && next < size) || Math.abs(next - size) > 0.3) setSize(next);
    }

    measure();

    // Наблюдать надо за СОСЕДЯМИ, а не только за собой, и это не
    // предосторожность. Кнопки в шапке появляются и исчезают сами:
    // «Установить» пропадает после установки, «Сбросить расположение» — после
    // сброса, «Подключить Telegram» — после подключения. В режиме своей
    // строки ширина цитаты всегда равна ширине шапки, то есть на пропавшую
    // кнопку не отзывается ничем, — и цитата осталась бы внизу навсегда,
    // хотя наверху освободилось место.
    const observer = new ResizeObserver(measure);
    observer.observe(box);
    const row = box.parentElement;
    if (row) {
      observer.observe(row);
      for (const el of Array.from(row.children)) if (el !== box) observer.observe(el);
    }
    return () => observer.disconnect();
  }, [size, ownRow]);

  return (
    <div className={"header-quote" + (ownRow ? " own-row" : "")} ref={boxRef} aria-hidden={!fits}>
      <span
        className="hqline"
        ref={lineRef}
        // visibility, а не display:none: скрытую строку нечем измерить, и
        // цитата, однажды не поместившаяся, никогда бы не вернулась.
        style={{ fontSize: size + "px", visibility: fits ? undefined : "hidden" }}
      >
        {QUOTE_HEAD}
        <b>{QUOTE_TAIL}</b>
      </span>
    </div>
  );
}
