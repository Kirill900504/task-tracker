import { NextResponse } from "next/server";

// Какая версия трекера сейчас на сайте.
//
// Открытое окно трекера живёт на том коде, с которым его открыли: вкладка,
// установленное приложение, окно на ПК. 07.10.2026 запрет встреч в
// прошлом выложили в 12:00, а в 12:13 встречу на 11:00 всё равно создали —
// из окна, открытого утром. Кирилл прочёл это как «по-прежнему позволяет»,
// и был прав: для него починки не существовало. Окно спрашивает здесь
// номер версии и, если он другой, перезагружается само (VersionWatch).
//
// Номер — тот же, что пишет журнал поломок (NEXT_PUBLIC_RELEASE, первые
// семь знаков коммита). Без входа: в нём нет ничего, кроме этих знаков.
export const dynamic = "force-dynamic";

export function GET() {
  return NextResponse.json(
    { release: process.env.NEXT_PUBLIC_RELEASE || "" },
    { headers: { "Cache-Control": "no-store" } },
  );
}
