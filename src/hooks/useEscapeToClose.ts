"use client";

import { useEffect } from "react";

// Escape закрывает то, что открыто. Везде.
//
// Кирилл сказал коротко: «некоторые разделы не закрываются кнопкой Esc,
// сделай чтобы любой раздел закрывался эскейпом». Он прав, и дело не в
// удобстве: Escape — единственный способ закрыть окно, не ища глазами
// крестик, и если он срабатывает через раз, им перестают пользоваться
// совсем. Раньше каждое окно заводило свой обработчик само, и потому
// половина окон его просто не завела: «Команда», меню отправки, меню
// карточки. Хук здесь один на всех — новое окно получает Escape,
// подключив его одной строкой, а не вспомнив про него.
//
// Слушаем в фазе ПЕРЕХВАТА и останавливаем событие: окна вкладываются
// друг в друга (вопрос поверх карточки задачи, меню роли поверх формы), и
// один Escape должен закрывать одно — верхнее. Обработчики навешиваются в
// порядке монтирования, но верхнее окно смонтировано позже и снимет
// событие первым только если само остановит его дальнейший путь.
//
// Порядок этот не абсолютный, и есть одно место, где на него полагаться
// нельзя: окно вопроса (Ask) живёт в корне приложения и смонтировано
// раньше всего, что его вызывает. Поэтому оно оставляет свой собственный
// обработчик — см. Ask.tsx.
export function useEscapeToClose(onClose: () => void, active = true) {
  useEffect(() => {
    if (!active) return;
    function onKeyDown(e: KeyboardEvent) {
      if (e.key !== "Escape") return;
      // Ввод в поле Escape не отменяет — он закрывает окно целиком, и это
      // то, чего от него ждут. Исключение — открытый список подсказок
      // браузера, который Escape закроет сам, до нас.
      e.stopPropagation();
      // И отменяем само нажатие, а не только его дальнейший путь.
      //
      // Остановить всплытие мало, когда то, что открыто, лежит ВНУТРИ
      // <dialog>: Escape там — «запрос на закрытие», и браузер шлёт окну
      // отдельное событие `cancel`, до которого stopPropagation не
      // достаёт. Один Escape закрывал тогда и меню, и окно под ним — то
      // есть меню роли уносило с собой форму задачи вместе со всем
      // набранным. preventDefault этот запрос снимает, а закрыть окно
      // по-прежнему есть чем: следующий Escape дойдёт до него самого.
      // Тот же случай уже был у календаря-шторки (MiniCalendar), там он
      // лечится своей парой строк — теперь это правило одно на всех.
      e.preventDefault();
      onClose();
    }
    document.addEventListener("keydown", onKeyDown, true);
    return () => document.removeEventListener("keydown", onKeyDown, true);
  }, [onClose, active]);
}
