// Чем доказан текущий вход — по полю `amr` подписанного токена сессии.
//
// Нужно для одного решения (29.10.2026): спрашивать ли ТЕКУЩИЙ пароль,
// прежде чем сменить пароль или почту входа. Спрашивать стоит, когда сессия
// получена ПАРОЛЕМ: оставленный открытым ноутбук иначе позволяет за десять
// секунд сменить пароль и почту и навсегда забрать вход себе. А вход через
// бота или по ссылке «новый пароль» уже доказал владение мессенджером —
// тем самым каналом, через который пароль восстанавливают, — и требовать у
// такого человека пароль, которого у него нет или который он как раз
// забыл, значило бы запереть его снаружи.
//
// Supabase пишет `amr` двумя формами: списком строк (RFC 8176) или списком
// объектов `{ method, timestamp }`. Читаем обе.
export type Amr = ({ method?: string } | string)[] | null | undefined;

export function signedInWithPassword(amr: Amr): boolean {
  return (amr || []).some((entry) => (typeof entry === "string" ? entry : entry?.method) === "password");
}

