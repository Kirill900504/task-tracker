// Поиск человека по имени — одно правило на все списки людей.
//
// Отзыв Витовского 25.09.2026: «когда будет здесь 30–40 человек, это будет
// прям портянка… сделать поле поиска», и про «+ добавить» у готовой задачи:
// «список выходит за рамки экрана». Списков людей в трекере три (кто на
// задаче, кого добавить, состав встречи), и правило совпадения у них должно
// быть одно — иначе в одном месте «нод» найдёт Нодберга, а в соседнем нет.
//
// Совпадение — по НАЧАЛУ любого слова имени: «нод», «юр», «юрий н». Имя
// стоит то впереди, то позади фамилии (см. peopleOrder), поэтому слово
// любое. «Ё» и «е» не различаются: их путают при наборе, а не в именах.

// Сколько людей должно быть в списке, чтобы поле поиска появилось вообще.
// На восьмерых оно — лишняя строка над восемью кнопками, которые и так
// видно разом.
export const SEARCH_FROM = 9;

function norm(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е").replace(/\(я\)/g, "").trim();
}

export function matchesPerson(name: string, query: string): boolean {
  const q = norm(query);
  if (!q) return true;
  const words = norm(name).split(/\s+/).filter(Boolean);
  const parts = q.split(/\s+/).filter(Boolean);
  // Каждое слово запроса — начало какого-то слова имени: «юр нод» находит
  // «Юрий Нодберг», а «нод юр» — его же.
  return parts.every((part) => words.some((w) => w.startsWith(part)));
}
