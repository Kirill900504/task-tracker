// Название — это о чём, а не что сказали.
//
// Фраза боту звучит как поручение: «Создай встречу на среду с участием
// Черкашина, Долгова, Есиной и Макарова, тема встречи — отдельный кабинет
// для настольного тенниса, а потом ещё обсудим маркировку остатков обуви».
// Модель, которой не сказали иначе, кладёт это целиком в title, и в
// календаре появляется строка на двести символов, начинающаяся со слова
// «Создай». Четыре такие строки в боевой базе и были — читать календарь
// после этого нельзя.
//
// Сказать модели, каким должен быть заголовок, — половина дела; вторая
// половина здесь, потому что правило проекта одно: не доверять модели того,
// что код может проверить сам. Это не «на всякий случай»: та же модель в
// плохой день вернёт ту же фразу, и единственное, что стоит между ней и
// календарём, — эта функция.

// Глаголы, которыми к боту обращаются. Снимается только НАЧАЛО строки:
// «создай» посреди названия — обычное слово («создай отдел» как тема), и
// трогать его нельзя.
const COMMAND = new RegExp(
  "^(?:" +
    [
      "созда(?:й|йте|ть)",
      "завед(?:и|ите)",
      "завести",
      "поставь(?:те)?",
      "поставить",
      "запиш(?:и|ите)",
      "записать",
      "добав(?:ь|ьте|ить)",
      "сдела(?:й|йте|ть)",
      "назнач(?:ь|ьте|ить)",
      "организу(?:й|йте|ировать)",
      "напомн(?:и|ите)",
      "оформ(?:и|ите|ить)",
    ].join("|") +
    ")\\s+",
  "i",
);

// Слово, которое идёт следом за глаголом и называет сам предмет: «создай
// ВСТРЕЧУ с Никитой» — «встречу» в названии встречи лишнее.
// Конец строки здесь — не мелочь: «Создай встречу» без темы после снятия
// обоих слов не оставляет ничего, и ниже это возвращает исходную фразу.
// Назвать такую встречу словом «Встречу» было бы хуже, чем не трогать.
const KIND = /^(?:встречу|встреча|задачу|задача|созвон|планёрку|планёрка|напоминание|заметку|мысль)(?:\s+|$)/i;

// Предлог, оставшийся на месте снятых слов: «…встречу НА среду» → «среду»
// читается хуже, чем ничего. Снимается только если после него ещё что-то
// есть.
const LEADING_PREP = /^(?:на|в|во|с|со|про|по|для|о|об)\s+(?=\S)/i;

const MAX = 80;

export function cleanTitle(raw: string): string {
  let s = (raw || "").replace(/\s+/g, " ").trim();
  if (!s) return "";

  // По одному разу каждое: «создай создай» — не тот случай, ради которого
  // стоит крутить цикл, а вот «создай встречу на» — ровно тот.
  if (COMMAND.test(s)) {
    s = s.replace(COMMAND, "");
    if (KIND.test(s)) s = s.replace(KIND, "");
    if (LEADING_PREP.test(s)) s = s.replace(LEADING_PREP, "");
  }
  s = s.trim();
  if (!s) return (raw || "").replace(/\s+/g, " ").trim();

  // Длинное название обрезается по границе слова и с многоточием: половина
  // слова в календаре выглядит как ошибка, а не как сокращение.
  if (s.length > MAX) {
    const cut = s.slice(0, MAX);
    const lastSpace = cut.lastIndexOf(" ");
    s = (lastSpace > MAX / 2 ? cut.slice(0, lastSpace) : cut).replace(/[,;:.\s]+$/, "") + "…";
  }

  return s.charAt(0).toUpperCase() + s.slice(1);
}
