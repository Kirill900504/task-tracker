import { createClient } from "@/lib/supabase/client";
import { storeShell } from "@/lib/shellCache";
import { WARM_PARAM } from "@/lib/warmParam";

// Трекер готовится, пока человек на странице входа (30.10.2026, «опять
// после входа прогружается долго!!!»).
//
// Замер на боевом: от «Войти» до живого трекера 5,7 с, и 2,8 из них уходили
// на то, чтобы ТОЛЬКО ПОСЛЕ входа начать качать файлы главной страницы. Пока
// человек набирает пароль (или подтверждает вход в мессенджере), сеть
// простаивает — значит готовить надо тогда. Готовится три вещи:
//
// 1. Файлы. Встроенная предзагрузка Next (`router.prefetch`) здесь не
//    работает: её запрос без сессии прослойка уводит на /login, а отличить его
//    от обычного она не может — Next стирает его заголовки до прослойки.
//    Поэтому оболочка «/» спрашивается со своим знаком (`?warm=1`,
//    пропускается прослойкой без сессии: это каркас без единой строки
//    данных), из неё берутся адреса файлов, и каждый скачивается один раз.
//    Дальше их отдают кэш браузера (они неизменяемые) и воркер
//    (`/_next/static` — сначала кэш, public/sw.js).
// 2. Сама оболочка. Она кладётся в кэш воркера как «/» (lib/shellCache), а
//    «/» воркер отдаёт сначала из кэша — значит переход после входа не ждёт
//    сервера вовсе: ни отрисовки, ни проверки сессии в прослойке (второй
//    замер: ~0,9 с между ответом «пароль верный» и первым кадром трекера).
// 3. Маршрут до базы. Клиент Supabase перед первым запросом проверяет,
//    доходит ли прямой хост (lib/supabase/client, проба до /sb), и делал это
//    в момент нажатия «Войти» — ещё ~0,5 с перед самой проверкой пароля.
//    Создать клиент заранее значит решить это, пока человек печатает.

export function assetUrls(html: string): string[] {
  const found = html.match(/\/_next\/static\/[^"'\s\\)]+\.(?:js|css)/g) ?? [];
  return [...new Set(found)];
}

let started = false;

export function warmTracker(): void {
  if (started || typeof window === "undefined") return;
  started = true;
  createClient();
  void (async () => {
    try {
      const res = await fetch(`/?${WARM_PARAM}=1`, { credentials: "same-origin" });
      if (!res.ok || res.redirected) return;
      void storeShell(res.clone());
      // Не все разом и не впереди того, что нужно странице входа сейчас.
      await Promise.all(assetUrls(await res.text()).map((u) => fetch(u, { priority: "low" } as RequestInit).catch(() => {})));
    } catch {
      /* без связи прогревать нечего — вход и так скажет об этом */
    }
  })();
}
