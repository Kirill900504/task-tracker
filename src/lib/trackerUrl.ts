// Адрес трекера, каким его видит человек снаружи.
//
// Нужен там, где ссылку собирает не браузер и не маршрут, отвечающий на
// запрос: кнопка «Открыть трекер» в мессенджере, вебхук, крон. Спросить
// заголовки (`originOf`) в этих местах не у чего — запроса от человека
// нет вовсе.
//
// Ничего настраивать для этого не надо, и это условие, а не удобство:
// правило проекта — не отправлять Кирилла в чужие панели за переменными
// (CLAUDE.md, «две кнопки и пароль»). Vercel задаёт свои переменные сам,
// а `NEXT_PUBLIC_SITE_URL` остаётся на случай, когда адрес окажется не
// тем, чего нам хочется (свой домен, ветка-предпросмотр).
//
// Порядок именно такой:
//   1. NEXT_PUBLIC_SITE_URL — если кто-то задал явно, он главнее всего.
//   2. VERCEL_PROJECT_PRODUCTION_URL — БОЕВОЙ адрес, одинаковый у всех
//      развёртываний. Именно он нужен кнопке: `VERCEL_URL` у каждого
//      развёртывания свой, одноразовый, и кнопка, собранная из него,
//      завтра ведёт на сборку, которой уже нет.
//   3. Known production host — последняя ниточка: функция, у которой нет
//      ни одной переменной, всё равно должна дать работающую ссылку, а
//      не пустую строку.
//
// С 29.10.2026 боевой адрес — свой домен компании, tracker.rokass.ru.
// `*.vercel.app` часть российских сетей режет по имени (CLAUDE.md), и
// ссылка из бота на него у половины людей открывалась белым экраном. На
// боевом развёртывании домен берётся отсюда, а не из
// VERCEL_PROJECT_PRODUCTION_URL: какой из доменов проекта Vercel назовёт
// «боевым», решает его панель, а не мы, и ошибка там молча вернула бы все
// ссылки на заблокированный адрес. Старый адрес при этом продолжает
// работать — у кого он открывался, у того ничего не сломалось.

const KNOWN_PRODUCTION = "https://tracker.rokass.ru";

export function trackerUrl(): string {
  const explicit = process.env.NEXT_PUBLIC_SITE_URL;
  if (explicit) return explicit.replace(/\/+$/, "");
  if (process.env.VERCEL_ENV === "production") return KNOWN_PRODUCTION;
  const production = process.env.VERCEL_PROJECT_PRODUCTION_URL;
  if (production) return `https://${production.replace(/\/+$/, "")}`;
  return KNOWN_PRODUCTION;
}

// Адрес мини-приложения. Отдельной функцией, а не строкой на месте:
// страница входа в мессенджере одна на Telegram и MAX, и её путь не
// должен быть написан в трёх файлах по-разному.
export function miniAppUrl(): string {
  return `${trackerUrl()}/app`;
}
