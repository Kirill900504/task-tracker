import { describe, expect, it } from "vitest";
import { orderWithAt, slotAt, type SectionSlot } from "./sectionOrder";

// Ряд из четырёх разделов в одну строку: центры через 100 пикселей.
const ROW: SectionSlot[] = [
  { id: "a", x: 100, y: 50 },
  { id: "b", x: 200, y: 50 },
  { id: "c", x: 300, y: 50 },
  { id: "d", x: 400, y: 50 },
];

const ids = ROW.map((s) => s.id);

// Один «шаг руки»: где оказался указатель — там и считается новый порядок.
function dragTo(from: string, x: number, y = 50): string[] {
  return orderWithAt(ids, from, slotAt(ROW, x, y, from));
}

describe("перестановка раздела считается по снимку ряда", () => {
  // Та самая ошибка, ради которой всё это вынесено отдельно.
  //
  // Раньше цель определялась по элементу под указателем, то есть по DOM,
  // который перестраивает React. Playwright — да и обычная мышь — успевают
  // прислать несколько движений раньше первой перерисовки, и каждое
  // следующее считалось по ряду, которого на экране уже нет: раздел
  // проезжал одну позицию и замирал. Здесь это воспроизведено буквально:
  // ОДНО движение через весь ряд, без единой перерисовки между.
  it("одно движение через весь ряд доводит раздел до начала", () => {
    expect(dragTo("d", 60)).toEqual(["d", "a", "b", "c"]);
  });

  it("одно движение через весь ряд доводит раздел до конца", () => {
    expect(dragTo("a", 460)).toEqual(["b", "c", "d", "a"]);
  });

  it("на полпути раздел встаёт ровно между соседями", () => {
    // Указатель между центрами b и c: пройдены a и b, сам «c» не в счёт.
    expect(dragTo("d", 250)).toEqual(["a", "b", "d", "c"]);
  });

  it("не сдвинувшись, порядок не меняется", () => {
    expect(dragTo("c", 300)).toEqual(ids);
  });

  // Ряд переносится на вторую строку, когда разделов много; «левее» имеет
  // смысл только внутри одной строки, иначе раздел, ведомый в начало
  // второй строки, считался бы стоящим перед всей первой.
  it("вторая строка ряда идёт после первой целиком", () => {
    const wrapped: SectionSlot[] = [
      { id: "a", x: 100, y: 50 },
      { id: "b", x: 200, y: 50 },
      { id: "c", x: 100, y: 90 },
      { id: "d", x: 200, y: 90 },
    ];
    // Указатель в начале ВТОРОЙ строки: первая пройдена целиком.
    expect(slotAt(wrapped, 60, 90, "d")).toBe(2);
    expect(orderWithAt(["a", "b", "c", "d"], "d", 2)).toEqual(["a", "b", "d", "c"]);
  });

  it("пустой ряд не двигает ничего", () => {
    expect(slotAt([], 100, 50, "a")).toBe(-1);
  });
});
