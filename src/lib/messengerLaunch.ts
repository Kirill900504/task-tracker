// Пришёл ли человек из мини-приложения — и чем он представился.
//
// Данные мессенджера живут во ФРАГМЕНТЕ адреса (после «#»), и это
// определяет половину устройства входа: фрагмент не уходит на сервер
// вовсе. Значит middleware о нём не знает, и человека без сессии он
// отправляет на /login — как отправил бы любого. Фрагмент при этом
// переживает редирект (браузер переносит его на цель, у которой своего
// нет), поэтому /login может посмотреть на него и увести дальше.
//
// Зачем такая петля, когда есть прямая ссылка на /app. Затем, что ссылку
// мини-приложения в кабинете MAX задаёт человек, а требования к ней
// перечисляют латиницу, цифры, точку и дефис — слэша в списке нет
// (dev.max.ru, «Подключение мини-приложения»). То есть поле может не
// принять путь, и тогда единственное, что туда влезет, — голый домен.
// С этим перехватом голый домен работает так же, как /app, и выбор
// ссылки перестаёт быть ставкой: ошиблись — всё равно войдёт.
//
// Telegram кладёт данные под именем `tgWebAppData`, MAX — под
// `WebAppData`. Проверяем оба, потому что перехват один на обоих.

export function hasMessengerLaunch(hash: string): boolean {
  const params = new URLSearchParams(hash.replace(/^#/, ""));
  return !!(params.get("tgWebAppData") || params.get("WebAppData"));
}

// Куда отправить такого человека, сохранив то, чем он представился.
// Фрагмент переносится как есть: разбирать его здесь незачем, этим
// занимается сама страница входа мессенджера.
export function miniAppRedirect(hash: string): string {
  return `/app${hash.startsWith("#") ? hash : "#" + hash}`;
}
