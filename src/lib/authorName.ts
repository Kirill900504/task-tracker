import { withoutSelfMark } from "@/lib/actorName";
import { isSelfAssignee } from "@/lib/trackerRows";

// Кто поставил задачу или собрал встречу — ИМЕНЕМ.
//
// В базе это `created_by`, то есть auth-id, и показать его нельзя. Имя
// лежит через одну таблицу (членство связывает логин со строкой человека),
// и это делает useAuthors. Пустой `created_by` при этом значит не «никто», а
// «владелец»: колонка появилась вместе с многопользовательской частью и его
// собственных строк не помечает — см. правило про «своё или чужое» в
// CLAUDE.md, которое однажды уже стоило Кириллу получаса чужой работы.
//
// Имя владельца берётся оттуда же, откуда его берёт весь остальной трекер:
// это строка в списке людей с пометкой «(я)». Пометка с экрана снимается —
// она написана для одного человека, а карточку читают все.
//
// Отдельной функцией, а не двумя строчками в каждой карточке, ровно потому,
// что «пусто = владелец» — правило, которое в этом проекте уже расходилось
// в четырёх местах сразу.
export function authorLabel(
  createdBy: string | undefined,
  authorsByUserId: Record<string, string>,
  people: string[],
): string {
  const id = (createdBy || "").trim();
  if (id) {
    const name = authorsByUserId[id] || "";
    // Логин есть, а имени нет — человека убрали из трекера после того, как
    // он поставил задачу. Сказать «—» было бы неправдой: постановщик был.
    return name ? withoutSelfMark(name) : "бывший участник";
  }
  const owner = people.find((p) => isSelfAssignee(p)) || "";
  return owner ? withoutSelfMark(owner) : "владелец";
}
