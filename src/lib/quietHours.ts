// Ночная тишина: с 22:00 до 8:00 по Москве.
//
// Правило касается только тех сообщений, которые трекер посылает сам —
// «вам назначена задача» и подобных. Отправленное человеком нажатием ✈ уходит
// сразу: он видит, который час, и решает сам; подменять его решение
// вежливостью было бы самоуправством.
//
// Ничего не теряется. Задача, назначенная ночью, всё равно попадёт в
// утреннюю сводку строкой «ждут вашего ответа» — то есть придёт в восемь
// утра, когда её и стоит читать.

const QUIET_FROM = 22;
const QUIET_UNTIL = 8;

// Россия живёт на UTC+3 без переводов часов с 2014 года: сдвиг метки и
// чтение UTC-полей даёт московское время без часовой библиотеки (тот же
// приём, что в taskLogic.moscowNow).
export function moscowHour(now: Date = new Date()): number {
  return new Date(now.getTime() + 3 * 60 * 60 * 1000).getUTCHours();
}

export function isQuietHour(now: Date = new Date()): boolean {
  const h = moscowHour(now);
  return h >= QUIET_FROM || h < QUIET_UNTIL;
}
