"use client";

import { flushSync } from "react-dom";

// Плавный переход вместо рывка.
//
// Вкладки на телефоне («Сегодня», «Задачи», «Встречи», «Мысли») менялись
// мгновенно: экран просто становился другим. На телефоне это читается как
// перезагрузка страницы — глазу не за что зацепиться, и непонятно, вперёд
// ты пошёл или назад.
//
// View Transitions — то, что для этого и сделано в браузере: он сам
// запоминает картинку до, картинку после и плавно переводит одну в другую.
// Двух строк CSS хватает на весь эффект, и ни одного кадра мы не рисуем
// сами.
//
// flushSync здесь обязателен и это не перестраховка: браузеру нужен снимок
// состояния ПОСЛЕ изменения, а React по умолчанию обновляет экран позже,
// когда переход уже начался и снимать нечего.
export function withViewTransition(update: () => void) {
  const start = (document as Document & { startViewTransition?: (cb: () => void) => void }).startViewTransition;
  // Браузер без переходов (или человек, отключивший анимации в системе)
  // получает то же самое, только мгновенно.
  if (typeof start !== "function" || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    update();
    return;
  }
  start.call(document, () => {
    flushSync(update);
  });
}
