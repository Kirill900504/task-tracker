// Своё или чужое — один ответ на весь трекер.
//
// Правило простое и ровно поэтому его четырежды написали чуть по-разному, а
// потом оно сломалось: у ВЛАДЕЛЬЦА `created_by` пуст у всего, что он завёл.
// Колонка появилась вместе с многопользовательской частью и его
// собственные строки не помечает. Строгое сравнение с его настоящим id
// объявляло чужой всю его работу — он не мог закрыть собственную задачу,
// перенести собственную встречу и записать итог собственной планёрки.
//
// Поэтому «я» здесь передаётся ПУСТЫМ для владельца, и пустое означает «всё
// моё». Руководителю передаётся его auth-id, и тогда своим считается то, что
// он сам и поставил.
//
// Держать это в одном месте важнее, чем кажется: правило решает, показывать
// ли кнопку, а кнопка, ведущая к отказу базы, обманывает молча — строка
// исчезает до перезагрузки и возвращается после неё.

export type Owned = { createdBy?: string };

export function isMine(item: Owned | null | undefined, myUserId: string): boolean {
  if (!myUserId) return true;
  if (!item) return true;
  return (item.createdBy || "") === myUserId;
}

// «Я действительно это завёл» — НЕ то же самое, что isMine().
//
// isMine() отвечает на вопрос прав редактирования: может ли этот человек
// править/закрывать/переносить эту строку, — и для владельца ответ «да»
// безусловно, потому что пространство его целиком, а не потому, что он
// автор именно этой записи. Эта функция отвечает на другой вопрос —
// «показать ли ему её как своё поручение» (счётчик «Я поручил», список
// «На приёмке», видимость чужой задачи) — и для владельца здесь важна
// РАЗНИЦА между его собственными строками (пустой created_by) и строками,
// которые завёл кто-то из руководителей (их настоящий id). Спутать эти две
// функции значило бы для владельца увидеть в «На приёмке» не только свои
// поручения, а вообще все задачи пространства, где он хоть кем-то
// числится, — именно та утечка, которую отловил itemVisibility.test.ts
// 23.09.2026, попытавшись переиспользовать здесь isMine().
export function isCreatedByMe(item: Owned | null | undefined, myUserId: string): boolean {
  if (!item) return true;
  return (item.createdBy || "") === myUserId;
}
