// Порядок людей на экране — один на весь трекер.
//
// Кирилл продиктовал его сам: Макаров, Долгов, Котов, Иванов, Есина,
// Витковский, Нодберг, Черкашин, Козлов, Мамакова, Головань, Синецкий,
// Ушанев, и тестовая учётная запись последней. Это не алфавит и не время
// добавления — это порядок, в котором он держит команду в голове, и именно
// поэтому им стоит пользоваться: список, отсортированный не так, как думает
// читающий, каждый раз перечитывают целиком.
//
// Сортируется по фамилии, а не по строке целиком: в базе лежат и «Евгений
// Макаров», и «Котов Михаил» — имя то впереди, то позади, и любая сортировка
// по первой букве разложила бы одних и тех же людей по-разному в разных
// списках. Тот, кого в списке нет, уходит в конец по алфавиту: новый человек
// не должен молча оказаться первым.

const ORDER = [
  "Макаров",
  "Долгов",
  "Котов",
  "Иванов",
  "Есина",
  "Витковский",
  "Нодберг",
  "Черкашин",
  "Козлов",
  "Мамакова",
  "Головань",
  "Синецкий",
  "Ушанев",
  // Владелец и тестовая учётная запись — в самом конце: их выбирают реже
  // всех, а места в начале они занимают столько же.
  "Кирилл",
];

function words(name: string): string[] {
  return String(name || "")
    .replace(/[()]/g, " ")
    .split(/\s+/)
    .map((w) => w.trim())
    .filter(Boolean);
}

// Место человека в списке. Незнакомых — в конец (ORDER.length).
export function personRank(name: string): number {
  for (const w of words(name)) {
    const i = ORDER.indexOf(w);
    if (i >= 0) return i;
  }
  return ORDER.length;
}

export function comparePeople(a: string, b: string): number {
  const ra = personRank(a);
  const rb = personRank(b);
  if (ra !== rb) return ra - rb;
  return a.localeCompare(b, "ru");
}

// Отсортировать что угодно, у чего есть имя, — список строк, список строк
// участия, список коллег.
export function sortByPeopleOrder<T>(list: T[], nameOf: (item: T) => string): T[] {
  return [...list].sort((a, b) => comparePeople(nameOf(a), nameOf(b)));
}

export function sortNames(names: string[]): string[] {
  return [...names].sort(comparePeople);
}
