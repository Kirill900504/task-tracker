import { describe, it, expect } from "vitest";
import { cleanTitle } from "./itemTitle";

// Настоящие фразы из боевой базы: именно так они туда и попали.

describe("название из сказанной фразы", () => {
  it("снимает обращение к боту вместе с названием предмета", () => {
    expect(cleanTitle("Создай встречу с Никитой Козловым на предмет закупок")).toBe(
      "Никитой Козловым на предмет закупок",
    );
  });

  it("снимает предлог, оставшийся на месте снятых слов", () => {
    expect(cleanTitle("Создай встречу на среду по маркировке остатков")).toBe("Среду по маркировке остатков");
  });

  it("обрезает длинное по границе слова", () => {
    const long =
      "Создай встречу на среду с участием Черкашина Долгова Есиной и Макарова тема встречи будет создание отдельного кабинета для настольного тенниса";
    const out = cleanTitle(long);
    expect(out.length).toBeLessThanOrEqual(81);
    expect(out.endsWith("…")).toBe(true);
    // Обрезано по пробелу, а не посреди слова.
    expect(out.slice(0, -1).endsWith(" ")).toBe(false);
    expect(out.startsWith("Среду с участием")).toBe(true);
  });

  it("обычное название не трогает", () => {
    expect(cleanTitle("Планёрка по закупкам")).toBe("Планёрка по закупкам");
    expect(cleanTitle("Согласовать скидку для Ростова")).toBe("Согласовать скидку для Ростова");
  });

  it("глагол внутри названия остаётся: снимается только обращение", () => {
    expect(cleanTitle("Обсудить, как создать отдел маркетинга")).toBe("Обсудить, как создать отдел маркетинга");
  });

  it("схлопывает пробелы и поднимает первую букву", () => {
    expect(cleanTitle("  поставь   задачу   собрать   отчёт  ")).toBe("Собрать отчёт");
  });

  it("из одного обращения название не выдумывает", () => {
    // Снять всё и вернуть пустоту значило бы завести запись без названия —
    // лучше оставить как есть, это хотя бы видно.
    expect(cleanTitle("Создай встречу")).toBe("Создай встречу");
  });

  it("пустое остаётся пустым", () => {
    expect(cleanTitle("")).toBe("");
    expect(cleanTitle("   ")).toBe("");
  });
});
