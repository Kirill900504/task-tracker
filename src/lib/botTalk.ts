// Живой разговор с ботом (22.10.2026, слова Кирилла: «мне нужна
// максимально общительная и умная версия в рамках работы трекера»).
//
// До этого на «привет», «спасибо», «как дела», «устал, завал» бот отвечал
// одной заготовкой — «Не понял, что сделать. Можно так: …» — то есть на
// человеческое слово инструкцией. Модель различала такие фразы и раньше
// (type=other), просто ответить ей было нечем.
//
// Устройство то же, что у сводок: факты пишет КОД, модель их оборачивает.
// `pulseFacts` — единственное, что ответ вправе сообщить о делах (сколько
// задач и встреч сегодня, что просрочено, ближайшая встреча), и
// `talkIsSafe` проверяет, что ни одного числа и ни одного названия сверх
// этого в ответе нет. Не прошёл — уходит заготовка того же смысла
// (`fallbackTalk`): бот, который сказал меньше, лучше бота, который
// пообещал встречу, которой нет.

// Факты дня одной строкой — то, что разговор может назвать.
export function pulseFacts(p: TrackerPulse | null): string {
  if (!p) return "";
  const bits: string[] = [];
  if (p.todayMeetings) bits.push(`${p.todayMeetings} ${plural(p.todayMeetings, "встреча", "встречи", "встреч")} сегодня`);
  if (p.nextMeeting) bits.push(`ближайшая в ${p.nextMeeting.time} — «${p.nextMeeting.title}»`);
  if (p.todayTasks) bits.push(`${p.todayTasks} ${plural(p.todayTasks, "задача", "задачи", "задач")} на сегодня`);
  if (p.overdue) bits.push(`${p.overdue} ${plural(p.overdue, "просроченная задача", "просроченные задачи", "просроченных задач")}`);
  return bits.length ? bits.join(", ") : "на сегодня ничего не запланировано и просрочек нет";
}

// Имя для обращения — первое слово: «Кирилл Кучеренко (я)» → «Кирилл».
export function firstName(full: string): string {
  return String(full || "")
    .replace(/\([^)]*\)/g, " ")
    .trim()
    .split(/\s+/)[0] || "";
}

