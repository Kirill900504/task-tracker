// Корни числительных до двенадцати — дальше в разговоре о дне числа
// словами не встречаются. «Одн» не берётся: «одна из них просрочена» —
// это «одна из трёх», а не новое число, и единица в фактах есть не всегда.
const NUMBER_WORDS: [RegExp, number][] = [
  [/(^|[^\p{L}])(дв(а|е|ух|ум)|пар[ау])(?=[^\p{L}]|$)/giu, 2],
  [/(^|[^\p{L}])тр(и|ех|ём|ем)(?=[^\p{L}]|$)/giu, 3],
  [/(^|[^\p{L}])четыр(е|ёх|ех)(?=[^\p{L}]|$)/giu, 4],
  [/(^|[^\p{L}])пят(ь|и)(?=[^\p{L}]|$)/giu, 5],
  [/(^|[^\p{L}])шест(ь|и)(?=[^\p{L}]|$)/giu, 6],
  [/(^|[^\p{L}])сем(ь|и)(?=[^\p{L}]|$)/giu, 7],
  [/(^|[^\p{L}])восем(ь|и)(?=[^\p{L}]|$)/giu, 8],
  [/(^|[^\p{L}])девят(ь|и)(?=[^\p{L}]|$)/giu, 9],
  [/(^|[^\p{L}])десят(ь|и)(?=[^\p{L}]|$)/giu, 10],
];

export function numberWordsToDigits(text: string): string {
  let out = text;
  for (const [re, n] of NUMBER_WORDS) out = out.replace(re, `$1${n}`);
  return out;
}

const COMMAND_QUOTE = /^«(перенеси|отложи|покажи|поторопи|напомни|поставь|запиши|поручи|верни|меню|сегодня|просрочено|встречи|мои задачи|что у меня)/i;

// Ответ модели годится, если он не длиннее разговора, не размечен и не
// сообщает о делах ничего сверх фактов: каждое число и каждое название в
// кавычках-ёлочках должны быть в строке фактов.
export function talkIsSafe(answer: string, facts: string): boolean {
  const text = answer.trim();
  if (!text || text.length > 420) return false;
  if (/[*_#`]{2,}|^\s*[-•]\s/m.test(text)) return false;
  if (text.startsWith("[") || text.startsWith("{")) return false;
  // Модель пишет числа и словами («две встречи», «три задачи») — сторож по
  // цифрам их бы не увидел. Слова переводятся в цифры перед сверкой.
  if (!rewriteIsFaithful(facts, numberWordsToDigits(text), [])) return false;
  // В ёлочках бывает два вида текста: название дела (только из фактов) и
  // фраза, которую можно написать боту («перенеси всё с сегодня на
  // завтра») — её отличает глагол-команда в начале.
  const titles = text.match(/«[^»]+»/g) || [];
  return titles.every((t) => facts.includes(t) || COMMAND_QUOTE.test(t));
}

// Заготовка на случай, когда модель молчит или ответила не по правилам.
// Смысл тот же — отозваться и показать день, — но словами кода.
export type TalkKind = "thanks" | "greeting" | "bye" | "tired" | "other";

export function talkKind(text: string): TalkKind {
  const t = text.toLowerCase();
  if (/спасиб|благодар|пасиб|спс\b|thank/.test(t)) return "thanks";
  if (/пока\b|до свидан|до завтра|хорошего вечера|спокойной ночи/.test(t)) return "bye";
  if (/устал|завал|не успева|тяжело|выгора|аврал|сил нет|запар/.test(t)) return "tired";
  if (/привет|здравств|добр(ое|ый|ой)\s+(утр|день|вечер)|хай\b|салют|здоров/.test(t)) return "greeting";
  return "other";
}

export function fallbackTalk(text: string, name: string, p: TrackerPulse | null): string {
  const kind = talkKind(text);
  const to = name ? `, ${name}` : "";
  const facts = pulseFacts(p);
  const day = facts ? ` На сегодня: ${facts}.` : "";
  switch (kind) {
    case "thanks":
      return `Пожалуйста${to}! Если что-то ещё — пишите как есть, разберу.`;
    case "bye":
      return `Хорошего${to}! Всё записанное никуда не денется — напомню, когда придёт время.`;
    case "tired":
      return `Понимаю${to}, бывает.${day} Могу показать просроченное или перенести часть дел — например: «перенеси всё с сегодня на завтра».`;
    case "greeting":
      return `Здравствуйте${to}!${day} С чего начнём?`;
    default:
      return `Я на связи${to}.${day} Пишите, что нужно: задачу, встречу, перенос или вопрос о делах.`;
  }
}

export async function talkReply(
  text: string,
  opts: { name: string; pulse: TrackerPulse | null; dialog: DialogLine[]; role: "assigner" | "recipient" },
): Promise<string> {
  const facts = pulseFacts(opts.pulse);
  try {
    const raw = await gigaChatComplete({
      system: systemPrompt(opts.name, facts, opts.dialog, opts.role),
      user: text,
      temperature: 0.7,
    });
    // Модель иногда заключает всю реплику в кавычки — снимаются только
    // такие, обрамляющие целиком, иначе с ними ушла бы ёлочка названия.
    let answer = raw.trim();
    if (/^"[\s\S]*"$/.test(answer)) answer = answer.slice(1, -1).trim();
    if (talkIsSafe(answer, facts)) return answer;
  } catch {
    // Модель недоступна — заготовка ниже отвечает тем же смыслом.
  }
  return fallbackTalk(text, opts.name, opts.pulse);
}
