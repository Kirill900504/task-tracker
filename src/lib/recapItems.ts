// Итог встречи → пункты для поручений.
//
// Предложение 4 от 13.10.2026, одобрено 14.10.2026: «итог встречи одной
// кнопкой превращается в задачи с исполнителями сразу, без
// перепечатывания». Итог пишут как придётся: строками, пунктами «-» или
// «1.», реже — одной строкой через точку с запятой. Каждый пункт становится
// строкой окна «Поручения из итога», где ему назначают человека и срок;
// ничего не создаётся без этого окна (правило «разобранное показывается и
// ждёт подтверждения»).
//
// Код, а не модель: разбить текст на строки — не вопрос понимания, и
// придумать пункт, которого в итоге не было, здесь нельзя.
export function recapItems(text: string): string[] {
  const clean = (text || "").replace(/\r/g, "").trim();
  if (!clean) return [];
  let lines = clean.split("\n");
  // Одна строка с точками с запятой — тоже список.
  if (lines.length === 1 && clean.includes(";")) lines = clean.split(";");
  return lines
    .map((l) =>
      l
        .trim()
        // Маркеры списка в начале: «-», «•», «*», «—», «1.», «1)».
        .replace(/^(?:[-•*—–]+|\d{1,2}[.)])\s*/, "")
        .trim(),
    )
    .filter((l) => l.length >= 2)
    .map((l) => l.slice(0, 200));
}
