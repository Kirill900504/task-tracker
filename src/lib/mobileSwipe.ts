// Жест «листнуть в соседний раздел» — арифметика отдельно от рук.
//
// На телефоне разделов пять, и переключаются они кнопками внизу. Свайп по
// содержимому — то, чего рука ждёт от любого мобильного приложения, и
// 22.09.2026 Кирилл попросил его прямо. Сложность в том, что горизонталь
// на этом экране уже занята: по карточке задачи свайп вправо закрывает её,
// влево открывает действия, а полосы фильтров и столбцов прокручиваются
// вбок. Два разных смысла одного движения — это способ гарантированно
// сделать не то, что хотели.
//
// Поэтому правило простое и записано здесь, а не по месту: жест считается
// «переключением раздела» только если он начался ТАМ, ГДЕ БОЛЬШЕ НИЧЕГО НЕ
// ЖДЁТ горизонтали. Что именно ждёт — перечислено списком: карточка с
// собственным жестом и всё, что прокручивается вбок само.

// Элементы, внутри которых горизонталь занята. Проверяется по цепочке
// родителей от точки касания: жест принадлежит ближайшему, кто о нём
// заявил, — то же правило, по которому устроены вложенные списки везде.
const BUSY = [
  ".swipe-wrap", // карточка задачи: свайп вправо — закрыть, влево — действия
  ".toolbar", // полоса над доской прокручивается вбок
  ".board-tabs", // столбцы доски — тоже
  ".section-tabs", // разделы: их ещё и переставляют перетаскиванием
  ".chat-msg", // реплика в обсуждении: по ней своё меню
  ".participant-grid", // люди в форме
  "input",
  "textarea",
  "[role=dialog]",
  "dialog",
];

export function startsInBusyArea(target: Element | null): boolean {
  if (!target) return false;
  return BUSY.some((sel) => target.closest(sel) !== null);
}

// Сколько пикселей считается намерением, а не дрожанием руки. Порог
// заметно больше, чем у свайпа по карточке (90): там жест начинается на
// самой карточке и ни с чем не спорит, а здесь он спорит с вертикальной
// прокруткой, которой пользуются постоянно.
export const SWIPE_PX = 70;
// И насколько движение должно быть горизонтальнее вертикального. Палец,
// ведущий список вверх, почти всегда уходит и вбок — без этого отношения
// разделы переключались бы при обычной прокрутке.
export const SWIPE_RATIO = 1.8;

export type SwipeVerdict = "none" | "next" | "prev";

export function verdict(dx: number, dy: number): SwipeVerdict {
  if (Math.abs(dx) < SWIPE_PX) return "none";
  if (Math.abs(dx) < Math.abs(dy) * SWIPE_RATIO) return "none";
  // Палец идёт влево — содержимое уезжает влево — приходит СЛЕДУЮЩИЙ
  // раздел. Так это работает везде, где листают страницы.
  return dx < 0 ? "next" : "prev";
}

// Сосед по списку разделов. Крайние не заворачиваются в кольцо нарочно:
// «Встречи» слева от «Задач» — это порядок, о котором договорились
// (он повторяет расположение блоков на компьютере), и прыжок с первого
// раздела на последний разрушил бы ощущение ряда.
export function neighbour<T>(tabs: readonly T[], current: T, where: SwipeVerdict): T | null {
  if (where === "none") return null;
  const at = tabs.indexOf(current);
  if (at < 0) return null;
  const next = where === "next" ? at + 1 : at - 1;
  return next >= 0 && next < tabs.length ? tabs[next] : null;
}
