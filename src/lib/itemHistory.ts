import type { SupabaseClient } from "@supabase/supabase-js";

// Хроника задачи: кто что сделал и когда.
//
// Состояние задачи отвечает на «что сейчас», и отвечает честно — но только
// на это. Возврат на доработку обнуляет отчёты (иначе задача навсегда
// осталась бы «отчитались все»), и вместе с ними исчезает то, что человек
// сдавал в первый раз. После второго круга уже никто не помнит, что именно
// просили доделать, — а спрашивают об этом всегда.
//
// Поэтому каждое событие, меняющее ход задачи, оставляет строку в её
// обсуждении. Не в новой таблице: обсуждение уже есть, уже показывает время
// и автора, уже видно всем участникам и уже доходит до мессенджеров. Ему не
// хватало только возможности сказать что-то не от имени человека — это и
// добавила миграция 0026.
//
// Что сюда НЕ пишется: правки текста и сроков. Они меняются часто и мимо
// этого кода (движок синхронизации), и строка на каждое нажатие превратила
// бы хронику в ленту, которую перестанут читать. Здесь только то, что
// кто-то ждал: принял, отчитался, отказался, попросил перенос, принято,
// возвращено, закрыто волевым.

export type ItemKind = "task" | "meeting";

export async function recordEvent(
  admin: SupabaseClient,
  event: { userId: string; kind: ItemKind; itemId: string; text: string },
): Promise<void> {
  // Молча: хроника — это польза, а не обязанность. Уронить отчёт человека
  // из-за того, что не записалась строка о нём, было бы обменом наоборот.
  const { error } = await admin.from("item_comments").insert({
    user_id: event.userId,
    item_kind: event.kind,
    item_id: event.itemId,
    body: event.text,
    source: "app",
    system: true,
  });
  if (error) console.error("item history:", error.message);
}
