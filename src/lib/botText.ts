// Пометка «(я)» у строки владельца в списке людей нужна ровно в одном
// месте — в трекере, чтобы он нашёл себя среди пятнадцати. В мессенджере
// её не должно быть нигде: ни в «Доброе утро, Кирилл Кучеренко (я)», ни в
// «срок был … — Кирилл Кучеренко (я)», ни в подписи кнопки. Он просил
// убрать её трижды, и каждый раз она возвращалась через новое сообщение,
// собранное из имени строки напрямую (withoutSelfMark в lib/actorName
// стоял только там, где о нём вспомнили).
//
// Поэтому снимается она на ВЫХОДЕ — в telegram.ts и max.ts, одним местом на
// все тексты, подписи кнопок и всплывашки. Данные кнопок (callback_data)
// не трогаются: это не текст, а адрес действия.
export function stripSelfMarks(text: string): string {
  return text.replace(/[  ]*\(я\)/gi, "");
}
