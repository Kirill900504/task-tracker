// Кому показать знакомство само.
//
// Новым — тем, чья учётная запись моложе месяца, — и один раз: отметка
// `tour_done` лежит в метаданных учётной записи, то есть переживает смену
// устройства (на телефоне и на ПК не спросят дважды). Кто в трекере давно,
// тем оно не навязывается — посмотреть можно кнопкой «Как пользоваться».
// Автотесты (navigator.webdriver) окно не получают: оно встало бы поверх
// доски в каждом из сотни тестов, а само окно проверяется открытием по
// кнопке.
export const TOUR_FRESH_DAYS = 30;

export function shouldShowTour(opts: { createdAt: string | undefined; done: boolean; now: number; automated: boolean }): boolean {
  if (opts.done || opts.automated || !opts.createdAt) return false;
  const age = opts.now - new Date(opts.createdAt).getTime();
  return age >= 0 && age < TOUR_FRESH_DAYS * 24 * 60 * 60 * 1000;
}
