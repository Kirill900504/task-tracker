// Кому показать знакомство само.
//
// Каждому — один раз на ВЕРСИЮ знакомства. Сперва (28.10.2026) оно было
// только для новых, чья учётная запись моложе месяца; тем же днём его
// слова: «сделай всем при следующем открытии знакомство с трекером. Чтобы
// все прошли его». Поэтому возраст учётной записи больше не спрашивается,
// а отметка — номер версии в метаданных учётной записи (`tour_version`):
// переживает смену устройства, а когда знакомство заметно дополнят,
// TOUR_VERSION поднимают на единицу, и его снова увидят все — ровно один
// раз. Прежняя отметка `tour_done: true` считается версией 1.
// Автотесты (navigator.webdriver) окно не получают: оно встало бы поверх
// доски в каждом из сотни тестов, а само окно проверяется открытием по
// кнопке.
export const TOUR_VERSION = 2;

export function seenTourVersion(meta: Record<string, unknown> | undefined): number {
  const v = Number(meta?.tour_version);
  if (Number.isFinite(v) && v > 0) return v;
  return meta?.tour_done === true ? 1 : 0;
}

export function shouldShowTour(opts: { seenVersion: number; automated: boolean }): boolean {
  return !opts.automated && opts.seenVersion < TOUR_VERSION;
}
