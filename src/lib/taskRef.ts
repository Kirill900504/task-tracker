// Как бот называет задачу: номер и название.
//
// 14.10.2026, его слова: «в мессенджеры обязательно надо добавить номера
// задач, для ориентира». Номер (миграция 0045) стоит на карточке в трекере
// и в первом сообщении о задаче, а дальше бот называл её только названием —
// и задачу с длинным названием приходилось узнавать, дочитав абзац до
// конца. Одна функция на все сообщения, чтобы «#12» везде выглядело
// одинаково и его можно было найти поиском в трекере (localSearch ищет
// именно «#12»).

export type TaskRefInput = { title: string; number?: number | null };

// «#12 «Смета»» — или просто «Смета» в кавычках, если номера ещё нет
// (строка не доехала до базы, старая задача без номера).
export function taskRef(task: TaskRefInput, limit = 0): string {
  const title = limit && task.title.length > limit ? task.title.slice(0, limit - 1).trimEnd() + "…" : task.title;
  return `${task.number != null ? `#${task.number} ` : ""}«${title}»`;
}

// Номер для подписи кнопки: «#12 Смета». Кнопка обрезается мессенджером,
// поэтому номер идёт первым — он и есть то, что должно остаться видно.
export function numbered(task: TaskRefInput): string {
  return task.number != null ? `#${task.number} ${task.title}` : task.title;
}
