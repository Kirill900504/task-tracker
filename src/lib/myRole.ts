import type { Task } from "@/types/tracker";
import type { TaskParticipant } from "@/lib/taskProgress";
import { isMine } from "@/lib/ownership";

// Чем эта задача является ДЛЯ МЕНЯ — и как это показать на доске.
//
// Правило Кирилла 19.09.2026, дословно: «выделенным фирменным цветом
// должны быть выделены задачи где человек является исполнителем… обычным
// тёмным тоном должны люди видеть свои задачи, где они соисполнители… и
// выбери ещё более лёгкий сероватый тон — для задач, где человек просто
// наблюдатель».
//
// Четвёртый случай он оставил на моё усмотрение: как показывать то, что
// поставил он сам, «среди всего аврала задач, при условии что там будут 14
// человек работать». Ответ — НЕ цветом, и это осознанное решение.
//
// Цвет на карточке уже несёт два смысла: мою роль и срок. Третий смысл
// сделал бы доску светофором — ровно тем «цветовым сыр-бором», которого он
// просил избежать в седьмом пункте. К тому же «я поставил» — это не
// свойство задачи, а режим, в котором на неё смотрят: сегодня я разбираю
// свою работу, завтра проверяю чужую. Поэтому авторство — это
// переключатель над доской («Мне / Я поручил / Все») плюс маленький значок
// исходящей стрелки в углу карточки, а цветом остаётся роль.

export type MyRole = "executor" | "coexecutor" | "watcher" | "none";

export function myRoleOn(participants: TaskParticipant[], meId: string): MyRole {
  if (!meId) return "none";
  const mine = participants.find((p) => p.assigneeId === meId);
  return mine ? mine.role : "none";
}

// Подсвечивать ли просрочку.
//
// «То что просрочено так же выделяется как и выделялось, для любой задачи
// для исполнителей и соисполнителей. Там где участник в роли наблюдателя
// выделять ничего не надо».
//
// Отдельно — задачи, которые я поставил другим: у них срок горит не мне, и
// красная карточка среди своих означала бы «ты не успел», хотя не успел не
// я. Такие считаются в цифру на переключателе «Я поручил» и подсвечиваются
// только внутри него — иначе доска у постановщика четырнадцати человек
// краснеет целиком и перестаёт что-либо значить.
export function showsOverdue(role: MyRole, isAuthorView: boolean): boolean {
  if (role === "executor" || role === "coexecutor") return true;
  if (role === "watcher") return false;
  // Ни исполнитель, ни соисполнитель, ни наблюдатель — значит это моё
  // поручение кому-то (или я владелец и смотрю на всё сразу).
  return isAuthorView;
}

// Что показывает доска: только моё, только мои поручения или всё подряд.
export type BoardView = "mine" | "assigned" | "all";

export function matchesView(
  view: BoardView,
  task: Task,
  role: MyRole,
  myUserId: string,
): boolean {
  if (view === "all") return true;
  if (view === "assigned") return isMine(task, myUserId);
  // «Мне» — то, где от меня чего-то ждут: исполнитель или соисполнитель.
  // Наблюдатель сюда не попадает: смотреть — не значит делать.
  return role === "executor" || role === "coexecutor";
}
