// Куда встанет раздел, если отпустить его здесь.
//
// Вынесено из SectionTabs отдельной функцией ровно потому, что ошибка
// здесь не видна ни глазом, ни типами: перестановка «почти работает» —
// раздел едет, просто не туда, — и заметить это можно только по тому, что
// после отпускания он оказался не там, куда его вели.
//
// Считается по СНИМКУ ряда, снятому в момент начала переноса, а не по
// тому, что сейчас под указателем. Раньше цель определял
// `document.elementFromPoint`, то есть настоящий DOM, который
// перестраивает React: пока перерисовка не случилась, следующее движение
// считалось по ряду, которого на экране уже нет, и шаг терялся. Плюс
// второй эффект того же устройства — после обмена перетаскиваемая кнопка
// встаёт ровно под указатель, а над собой обмена не бывает, значит для
// следующего шага надо физически выйти за её край. Вместе это давало то,
// что видно рукой: берёшь раздел, ведёшь через три соседних, отпускаешь —
// он сдвинулся на один. Мышью так происходило всегда, потому что рука
// движется быстрее, чем идут кадры.
//
// Снимок не устаревает, потому что отвечает на другой вопрос: не «что
// сейчас под пальцем», а «между какими из НАЧАЛЬНЫХ мест указатель
// находится». Эти места никуда не деваются, сколько бы раз предпросмотр ни
// перерисовался.

export type SectionSlot = { id: string; x: number; y: number };

// Снимок ряда целиком: места кнопок и то, где стоял сам ряд в тот момент.
//
// Второе — не мелочь. Пока человек ведёт раздел, страница может уехать:
// сработала прокрутка, появилась плашка «1 на сегодня», закрылся тост, —
// и ряд оказывается на сорок пикселей ниже, чем был. Места в снимке при
// этом остались прежними, то есть указатель и снимок начинают говорить о
// разных экранах: рука над рядом, а по снимку она уже под ним. Раздел
// после этого встаёт куда угодно, и выглядит это как «перетаскивание
// сработало наполовину».
// Поэтому координаты указателя приводятся к системе снимка — вычитается
// то, на сколько успел уехать сам ряд.
export type SectionSnapshot = { slots: SectionSlot[]; rowX: number; rowY: number };

// Насколько центры должны разойтись по вертикали, чтобы считаться разными
// строками ряда. Кнопки одной строки стоят центр в центр, так что порог
// щедрый: половина высоты кнопки хватает с запасом.
const ROW_GAP = 14;

// Куда встанет раздел. Координаты указателя — экранные; сдвиг самого ряда
// с момента снимка снимается здесь же.
export function slotAt(snap: SectionSnapshot, pointerX: number, pointerY: number, dragId: string, rowX: number, rowY: number): number {
  const slots = snap.slots;
  const x = pointerX - (rowX - snap.rowX);
  const y = pointerY - (rowY - snap.rowY);
  if (!slots.length) return -1;
  // Место пройдено, если оно на строке выше указателя или на той же строке
  // левее его. Разделы переносятся на несколько строк, и «левее» имеет
  // смысл только внутри одной.
  const passed = slots.filter((s) => (Math.abs(s.y - y) > ROW_GAP ? s.y < y : s.x < x));
  // Сам перетаскиваемый в счёт не идёт: позиция считается в списке БЕЗ
  // него, иначе раздел, ведомый вправо, не доезжал бы до последнего места.
  return passed.length - (passed.some((s) => s.id === dragId) ? 1 : 0);
}

// Новый порядок целиком. Строится от ИСХОДНОГО порядка, а не от
// предыдущего предпросмотра: позиция уже посчитана по снимку начального
// ряда, и накладывать её на уже переставленный список значило бы считать
// дважды.
export function orderWithAt(base: string[], dragId: string, slot: number): string[] {
  const rest = base.filter((id) => id !== dragId);
  const at = Math.max(0, Math.min(slot, rest.length));
  return [...rest.slice(0, at), dragId, ...rest.slice(at)];
}
