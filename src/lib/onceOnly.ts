import type { SupabaseClient } from "@supabase/supabase-js";

// «Это уже отправляли» — один раз на весь крон.
//
// Напоминания и сводки проверяет внешний пингер каждые несколько минут, а
// отправить их надо по одному разу. Приём везде один и тот же и держится на
// уникальном ключе: пробуем вставить строку в telegram_notifications, и если
// вставка не прошла — значит, это уже сделано, выходим. Никакого «прочитали,
// потом записали»: два вызова крона могут наложиться, и тогда человек
// получит сводку дважды.
//
// Приём правильный, но был выписан семь раз подряд — с разными именами
// переменных, где-то с try/catch, где-то без. Разница нигде не была
// осознанной, а семь копий одного условия — это семь мест, где однажды
// забудут `notif_date` и обнаружат это по второму письму в день.
//
// Дата — не то же самое, что ключ: ref_id говорит «о чём», notif_date —
// «за какой день», и вместе они и есть «однажды».

export async function onceOnly(
  admin: SupabaseClient,
  mark: { userId: string; kind: string; refId: string; date: string },
  run: () => Promise<void>,
): Promise<boolean> {
  const { error } = await admin.from("telegram_notifications").insert({
    user_id: mark.userId,
    kind: mark.kind,
    ref_id: mark.refId,
    notif_date: mark.date,
  });
  // Любая ошибка вставки читается как «уже отправлено». Это осознанно:
  // ошибиться в сторону молчания здесь дешевле, чем разбудить человека
  // второй раз тем же самым.
  if (error) return false;

  // Упасть внутри — не повод уронить весь крон: дальше по списку ещё
  // тринадцать человек, которым их напоминания нужны не меньше.
  try {
    await run();
  } catch (e) {
    console.error(`${mark.kind} failed:`, e);
  }
  return true;
}
