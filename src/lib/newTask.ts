// Как выглядит только что заведённая задача — один ответ на всех.
//
// Заводить задачи на сервере умеют четыре места: бот по фразе, разбор
// надиктованного совещания, «взять мысль в работу» в трекере и та же кнопка
// в мессенджере. Каждое собирало строку само, и умолчания у них разошлись:
// где-то `term` был "short", где-то его не было вовсе (и Postgres ставил
// своё), где-то `recur` заполнялся, где-то нет, а `created_by` проставляли
// два места из четырёх — из-за чего уведомление об отчёте не знало, кому
// адресоваться (см. notifyAuthor).
//
// Разница нигде не была осознанной. Она просто накапливалась, пока каждое
// место писали отдельно, и вылезала не там, где её сделали: задача, заведённая
// голосом, вела себя чуть иначе, чем та же задача из карточки.
//
// Поле `assignee` здесь — не украшение: с миграции 0024 имя, за которым стоит
// известный человек, само заводит строку участия. Уведомить его это не может,
// поэтому рядом всё равно нужен attachExecutors.
//
// Идентификатор передаётся снаружи, а не делается здесь: его приставка
// говорит, откуда задача взялась («bot…», «tg…», «t…»), и однажды это
// оказалось единственным, по чему удалось найти путь, терявший исполнителей.

import { isoDate, workdayIn } from "@/lib/whenDate";

// Срок по умолчанию — через неделю, рабочим днём.
//
// Срок обязателен у любой задачи (14.10.2026: «запрети ставить задачи без
// срока даже самому себе, срок обязателен»). Форма трекера просто не
// сохранит задачу без него, а у бота спросить «на когда?» можно не всегда:
// надиктованный после встречи список из пяти пунктов, где срок не назван
// ни у одного, не превращают в пять вопросов. Поэтому сервер ставит
// неделю — то же предложение 7 из разбора 13.10.2026, «мягкий срок по
// умолчанию», одобренное им, — а каждый ответ бота, где срок поставлен
// так, говорит об этом вслух (`deadlineNote`), чтобы его можно было
// поправить. Неделя, а не «завтра»: срок, который никто не назначал, не
// должен с первого дня гореть.
export function defaultDeadline(now: Date = new Date()): string {
  return isoDate(workdayIn(now, 7));
}

// Что сказать в ответе бота, если срок поставил сервер, а не человек.
export function deadlineNote(given: string | null | undefined, now: Date = new Date()): string {
  if (given) return "";
  const [y, m, d] = defaultDeadline(now).split("-");
  return `Срок не назвали — поставил ${d}.${m}.${y}, через неделю: поменять его можно в карточке задачи.`;
}

export type NewTaskRow = {
  id: string;
  user_id: string;
  title: string;
  description: string;
  assignee: string;
  // Колонка осталась в базе, но трекер её больше не показывает и не
  // спрашивает (20.09.2026: «удали везде приоритетности»), поэтому
  // newTaskRow всегда пишет "med". Тип оставлен широким нарочно: по нему
  // ещё читают строки, заведённые до этого дня.
  priority: "high" | "med";
  term: "short" | "long";
  status: "in_progress";
  deadline: string | null;
  recur: "none";
  created_by: string | null;
};

export function newTaskRow(input: {
  id: string;
  userId: string;
  title: string;
  description?: string;
  assignee?: string;
  // Принимается и игнорируется: у зовущих (разбор фразы в боте) поле ещё
  // встречается в старых данных, и падать из-за него незачем.
  priority?: string;
  term?: string;
  deadline?: string | null;
  // Кто поручил. Пусто означает владельца пространства — так это и читает
  // notifyAuthor.
  createdBy?: string | null;
}): NewTaskRow {
  return {
    id: input.id,
    user_id: input.userId,
    title: input.title,
    description: input.description || "",
    assignee: (input.assignee || "").trim(),
    priority: "med",
    term: input.term === "long" ? "long" : "short",
    // Новая задача всегда в работе: «done» у только что созданной означало
    // бы, что её завели уже сделанной, и такого пути здесь нет.
    status: "in_progress",
    // Срок обязателен: не назван — неделя (см. defaultDeadline).
    deadline: input.deadline || defaultDeadline(),
    recur: "none",
    created_by: input.createdBy || null,
  };
}
