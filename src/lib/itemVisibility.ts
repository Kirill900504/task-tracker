import type { Meeting, Task } from "@/types/tracker";
import { isCreatedByMe } from "@/lib/ownership";

// Видит ли ТЕКУЩИЙ человек эту задачу или встречу — вообще, до всякого
// переключателя «Мне / Я поручил / Все» на доске.
//
// Правило Кирилла 23.09.2026, дословно: «каждый видит только свои
// поставленные конкретным людям и себе задачи, а так же видит те события
// которые поставили ему… Все остальные не касающиеся конкретного участника
// события задачи и встречи участник видеть не должен, чтобы не засорялся
// эфир. Это правило касается и меня!» — то есть без исключения для
// владельца, которому раньше было видно всё пространство сразу (см. старое
// правило «Трекер один на всех» в CLAUDE.md, которое это отменяет).
//
// Вынесено в чистую функцию, а не оставлено внутри NewTracker.tsx, по той
// же причине, по которой здесь чистые matchesView/isMine/columnOf: это
// граница приватности данных, а не деталь одного экрана, и однажды здесь
// уже была настоящая утечка (мысли, 23.09.2026) — цена ошибки в такой
// функции выше, чем в обычной вёрстке, и она обязана быть покрыта тестом,
// который переживёт любую перестройку интерфейса вокруг неё.

// Постановщик — isCreatedByMe(), НЕ isMine(): у видимости другой вопрос,
// чем у прав редактирования, и isMine() для владельца ответила бы «моё»
// на вообще любую задачу пространства (см. комментарий у isCreatedByMe в
// lib/ownership.ts — это и есть баг, который поймал тест на этот файл при
// первой же попытке использовать здесь isMine). Участник — любая роль на
// задаче: исполнитель, соисполнитель ИЛИ наблюдатель — здесь все три
// равны, разница между ними в том, что каждый может НА задаче делать, а
// не в том, видна ли она вообще.
export function isTaskVisible(task: Task, myUserId: string, myAssigneeId: string, participantAssigneeIds: string[]): boolean {
  if (isCreatedByMe(task, myUserId)) return true;
  if (!myAssigneeId) return false;
  return participantAssigneeIds.includes(myAssigneeId);
}

// У встречи участники — готовый список ИМЁН прямо на строке (в отличие от
// задачи, где роли живут в отдельной таблице task_participants), поэтому
// здесь сравнение проще: организатор — isCreatedByMe, приглашённый — имя
// в списке.
export function isMeetingVisible(meeting: Meeting, myUserId: string, myName: string): boolean {
  if (isCreatedByMe(meeting, myUserId)) return true;
  if (!myName) return false;
  return meeting.participants.includes(myName);
}
