// Темы — в подсказку модели: ключ и одна строка о том, когда его выбрать.
export function guideTopicsForPrompt(): string {
  return Object.entries(GUIDE)
    .map(([key, t]) => `${key} — ${t.title.toLowerCase()}`)
    .join("; ");
}

// Ответ на «как…?»: тема целиком. Неизвестная тема — не выдумка, а
// оглавление: лучше показать, что есть, чем гадать.
export function guideAnswer(topic: string, who: "assigner" | "recipient"): string {
  const t = GUIDE[topic];
  if (!t) return guideIndex(who);
  const lines = [t.title, "", ...t.bot.map((b) => "• " + b)];
  if (t.tracker) lines.push("", t.tracker);
  if (t.who === "assigner" && who === "recipient") lines.push("", "Это делает тот, кто поставил задачу или назначил встречу.");
  return lines.join("\n");
}

// Оглавление — «о чём можно спросить».
export function guideIndex(who: "assigner" | "recipient"): string {
  const titles = Object.values(GUIDE)
    .filter((t) => who === "assigner" || t.who !== "assigner")
    .map((t) => "• " + t.title);
  return ["Спросите меня «как…» про любое из этого — расскажу:", "", ...titles].join("\n");
}
