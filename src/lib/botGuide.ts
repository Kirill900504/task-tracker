// Что бот знает о самом трекере — справочник, написанный кодом.
//
// Аудит ботов 20.10.2026 (просьба Кирилла: «они должны знать всё о текущем
// функционале трекера и быть лучшими помощниками»). Бот умел многое, но
// рассказать об этом не мог: «помощь» перечисляла четыре слова и
// поручения, а на вопрос «как отложить задачу?» или «можно ли позвать
// человека на встречу?» отвечать было нечем — вопрос уходил в шаг,
// который знает ДАННЫЕ трекера («что у меня завтра»), а не его УСТРОЙСТВО.
//
// Почему справочник, а не просьба к модели «объясни»: правило проекта —
// модель не пишет фактов (см. «The model does not do arithmetic or
// facts» в CLAUDE.md). Описание трекера — тоже факты, и придуманная
// моделью кнопка «Делегировать» отправила бы человека искать то, чего нет.
// Поэтому модель только выбирает ТЕМУ из закрытого списка (`type:"howto"`
// в quickAdd), а слова — отсюда. Одна правда на два места: из этих же
// тем собирается «помощь» (`assignerHelp`, `colleagueCommandsHelp`).
//
// Добавляя умение боту или кнопку трекеру, допишите тему сюда — иначе
// бот снова будет уметь то, о чём не может сказать.

