import type { MyRole } from "@/lib/myRole";

// Чем задача является ДЛЯ МЕНЯ — одним словом, из которого кубик берёт
// весь свой вид.
//
// Слова Кирилла 13.10.2026: «задачи (где я постановщик), поставленные
// другому человеку или группе лиц, должны подсвечиваться основным
// фирменным стилем… задачи, поставленные на самого себя, должны у всех
// отличаться визуально… выразительная, но спокойная… поставленные мне
// задачи тоже должны иметь свой отличительный приятный дизайн. Задачи, где
// человек соисполнитель и наблюдатель, — менее выраженно».
//
// До этого вид считался по одной только роли, и фирменная заливка
// доставалась ИСПОЛНИТЕЛЮ — то есть в первую очередь задачам самому себе
// (в них я всегда исполнитель), а поручения, ради которых трекер и
// заведён («поставил десятерым и помню двоих»), стояли серыми. Авторство
// раньше нарочно не показывалось цветом (lib/myRole, 19.09.2026); теперь
// он сам назвал его первым, и это главный вопрос к доске постановщика.
//
// Порядок проверок и есть правило:
//   self     — поставил я, и на задаче нет никого, кроме меня (lib/selfTask);
//   outgoing — поставил я, на задаче есть другие (в любой моей роли: «я
//              поручил» важнее, чем «я ещё и помогаю»);
//   incoming — поставили мне, я исполнитель;
//   co       — помогаю;
//   watch    — смотрю;
//   none     — вижу, но ни при чём (встречается редко: видимость личная).
//
// Как каждый вид выглядит, решено вторым кругом 14.10.2026 (task-ui.css):
// заливка только у outgoing; self — жирная тёплая полоса и «Личная задача»;
// incoming — фирменная рамка без заливки; co — жирная фирменная полоса и
// «Помогаю»; watch — цветной глаз и «Наблюдаю». Метки — в правом нижнем углу.
export type CardKind = "self" | "outgoing" | "incoming" | "co" | "watch" | "none";

export function cardKind(opts: { authored: boolean; selfTask: boolean; role: MyRole }): CardKind {
  if (opts.selfTask) return "self";
  if (opts.authored) return "outgoing";
  if (opts.role === "executor") return "incoming";
  if (opts.role === "coexecutor") return "co";
  if (opts.role === "watcher") return "watch";
  return "none";
}

// Подсказка на наведение: цвет отвечает быстрее подписи, но не отвечает,
// КЕМ я в задаче числюсь.
export const CARD_KIND_HINT: Record<CardKind, string | undefined> = {
  self: "Ваша личная задача",
  outgoing: "Вы поручили",
  incoming: "Поручили вам",
  co: "Вы соисполнитель",
  watch: "Вы наблюдатель",
  none: undefined,
};
