import { describe, expect, it } from "vitest";
import { comparePeople, personRank, sortNames } from "@/lib/peopleOrder";

describe("порядок людей", () => {
  it("тот самый, который продиктовал Кирилл", () => {
    const shuffled = [
      "Наталья Есина",
      "Сергей Головань",
      "Игорь Витковский",
      "Юрий Нодберг",
      "Евгений Макаров",
      "Станислав Синецкий",
      "Наталья Мамакова",
      "Михаил Иванов",
      "Котов Михаил",
      "Юрий Черкашин",
      "Никита Долгов",
      "Никита Ушанев",
      "Никита Козлов",
      "Кирилл (тест)",
    ];
    expect(sortNames(shuffled)).toEqual([
      "Евгений Макаров",
      "Никита Долгов",
      "Котов Михаил",
      "Михаил Иванов",
      "Наталья Есина",
      "Игорь Витковский",
      "Юрий Нодберг",
      "Юрий Черкашин",
      "Никита Козлов",
      "Наталья Мамакова",
      "Сергей Головань",
      "Станислав Синецкий",
      "Никита Ушанев",
      "Кирилл (тест)",
    ]);
  });

  // Имена в базе приведены к виду «Имя Фамилия» 21.09.2026, но свойство
  // проверяется дальше: заведут человека как «Петров Иван» — и порядок
  // слов не должен решать, где он окажется в списке.
  it("находит фамилию, где бы она ни стояла", () => {
    expect(personRank("Котов Михаил")).toBe(personRank("Михаил Котов"));
    expect(personRank("Михаил Иванов")).toBeGreaterThan(personRank("Котов Михаил"));
  });

  it("незнакомых ставит в конец и по алфавиту", () => {
    const sorted = sortNames(["Яна Яковлева", "Евгений Макаров", "Анна Новая"]);
    expect(sorted).toEqual(["Евгений Макаров", "Анна Новая", "Яна Яковлева"]);
  });

  it("владелец и тестовая запись — последние из своих", () => {
    expect(comparePeople("Кирилл (я)", "Никита Ушанев")).toBeGreaterThan(0);
  });
});
