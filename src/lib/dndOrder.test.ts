import { describe, it, expect } from "vitest";
import { insertBefore, moveWithin, sameOrder } from "@/lib/dndOrder";

// Эти двадцать строк стоили боевой версии: 19.09.2026 трекер падал в белый
// экран, стоило потянуть задачу в столбце, где лежит больше одной. React
// сообщал об этом как «Minified React error #185» — превышена глубина
// обновлений, то есть бесконечная петля перерисовки.
//
// Петля собиралась из двух безобидных половин: предпросмотр вставлял
// карточку ПЕРЕД той, над которой курсор, — и после вставки под курсором
// оказывалась она сама. «Вставить перед собой» тогда означало «в конец»,
// карточка уезжала вниз, под курсором снова оказывалась прежняя соседка, и
// круг замыкался. Поэтому здесь проверяется не только обычный порядок, но
// и оба вырожденных случая: «над собой» и «над тем, чего в списке нет».

describe("insertBefore", () => {
  it("ставит перед указанным соседом", () => {
    expect(insertBefore(["a", "b", "c"], "c", "b")).toEqual(["a", "c", "b"]);
  });

  it("без соседа ставит в конец", () => {
    expect(insertBefore(["a", "b", "c"], "a", null)).toEqual(["b", "c", "a"]);
  });

  it("добавляет того, кого в списке ещё не было", () => {
    expect(insertBefore(["a", "b"], "x", "b")).toEqual(["a", "x", "b"]);
  });

  it("«перед самим собой» ничего не меняет — иначе карточка уезжала в конец", () => {
    expect(insertBefore(["a", "b", "c"], "b", "b")).toEqual(["a", "b", "c"]);
  });

  it("«перед самим собой» для новичка означает «в конец»", () => {
    expect(insertBefore(["a", "b"], "x", "x")).toEqual(["a", "b", "x"]);
  });
});

describe("moveWithin", () => {
  it("вниз: встаёт НА место соседа, а не перед ним", () => {
    expect(moveWithin(["a", "b", "c", "d"], "a", "c")).toEqual(["b", "c", "a", "d"]);
  });

  it("вверх: тоже встаёт на место соседа", () => {
    expect(moveWithin(["a", "b", "c", "d"], "d", "b")).toEqual(["a", "d", "b", "c"]);
  });

  it("над самим собой — ничего не двигает", () => {
    expect(moveWithin(["a", "b", "c"], "b", "b")).toEqual(["a", "b", "c"]);
  });

  it("над пустотой — ничего не двигает", () => {
    expect(moveWithin(["a", "b", "c"], "b", null)).toEqual(["a", "b", "c"]);
  });

  it("чужого в списке не двигает", () => {
    expect(moveWithin(["a", "b"], "x", "a")).toEqual(["a", "b"]);
  });
});

describe("sameOrder", () => {
  it("видит совпадение и расхождение", () => {
    expect(sameOrder(["a", "b"], ["a", "b"])).toBe(true);
    expect(sameOrder(["a", "b"], ["b", "a"])).toBe(false);
    expect(sameOrder(["a"], ["a", "b"])).toBe(false);
  });
});
