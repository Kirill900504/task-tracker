// Что бот говорит про время встречи и про опоздавших.
//
// Три набора фраз, и все три — просьба Кирилла 20.09.2026: предупредить,
// что время кончается; сказать, что кончилось («бегом работать, хватит
// болтать» — его слова); и дать организатору кнопку поторопить тех, кто
// не пришёл.
//
// Почему фразы лежат отдельным файлом и почему их несколько. Одна и та же
// шутка, приходящая каждый вторник, через месяц читается как упрёк, а
// через два её перестают видеть вовсе — как и любое повторяющееся
// уведомление. Набор из нескольких строк и выбор по номеру встречи
// (а не случайный) дают две вещи сразу: сообщение не приедается, и при
// этом оно одинаково у всех участников одной встречи — иначе Есина и
// Мамакова прочитали бы разное и пошли уточнять друг у друга.
//
// Тон выбран так, чтобы шутка была про ВРЕМЯ, а не про человека.
// Опоздание — самое обидное, что тут можно задеть: «опять ты» звучит
// оскорбительно даже от бота, поэтому в этих строках подгоняют встречу,
// а не характер.

// Устойчивый выбор: одна встреча — одна фраза, но у соседней она другая.
// Номер считается из идентификатора, поэтому не зависит ни от времени
// отправки, ни от того, кому из участников уходит сообщение.
function pick(list: string[], seed: string): string {
  let sum = 0;
  for (let i = 0; i < seed.length; i++) sum = (sum + seed.charCodeAt(i) * (i + 1)) % 100000;
  return list[sum % list.length];
}

const ENDING_SOON = [
  "Время встречи заканчивается. Последние решения — и расходимся.",
  "Финишная прямая: пора договориться, кто что делает дальше.",
  "Осталось немного. Успеть бы записать, о чём договорились.",
  "Подводим итог: что решили и кто за это берётся?",
];

// Конец времени. Шутка здесь допустима именно потому, что она ни к кому
// не обращена лично: закончилось время, а не чьё-то терпение.
const TIME_IS_UP = [
  "⏰ Время вышло. Бегом работать, хватит болтать!",
  "⏰ Час прошёл. Всё, что не решили за это время, решается делом, а не разговором.",
  "⏰ Время закончилось. Самая длинная встреча всё равно короче самой короткой сделанной задачи.",
  "⏰ Стоп. Совещание, которое длится дольше плана, обсуждает уже само себя.",
  "⏰ Время вышло. Расходимся — работа ждёт.",
  "⏰ Конец. Кто не успел сказать — напишите в обсуждение, оно никуда не денется.",
];

// Поторопить тех, кого нет. Обращено к встрече, а не к человеку: «вас
// ждут» вместо «вы опять опоздали».
const LATECOMERS = [
  "🙋 Вас ждут на встрече «{title}». Все уже на месте.",
  "⏳ Встреча «{title}» идёт, не хватает только вас.",
  "📣 Напоминаем про «{title}» — начали без вас, но ждём.",
  "🚪 «{title}»: дверь открыта, место за столом ваше.",
];

export function endingSoonText(title: string, endsAt: string, seed: string): string {
  return `⏳ «${title}» заканчивается в ${endsAt}.\n\n${pick(ENDING_SOON, seed)}`;
}

export function timeIsUpText(title: string, seed: string): string {
  return `${pick(TIME_IS_UP, seed)}\n\nВстреча «${title}» — время закончилось.`;
}

export function latecomerText(title: string, seed: string): string {
  return pick(LATECOMERS, seed).replace("{title}", title);
}

// Участник напоминает организатору об итоге прошедшей встречи.
//
// Просьба Кирилла 07.10.2026: закрыть прошедшую встречу может только тот,
// кто её собрал, а у остальных она так и висит в списке с плашкой «нужен
// итог» — убрать её участник не в силах. Кнопка «Напомнить» на карточке
// отдаёт этот вопрос тому, кто может на него ответить. Шутка — про итог и
// про встречу, а не про забывчивость организатора: по тем же причинам,
// что выше, и ещё по одной — пишет это не бот, а коллега, и упрёк от
// коллеги, повторённый ботом, звучит вдвойне.
const RECAP_NUDGES = [
  "📝 Встреча «{title}» закончилась, а итог всё ещё ищет, куда ему записаться.",
  "🕵️ Говорят, на встрече «{title}» о чём-то договорились. О чём именно — знает только организатор.",
  "📜 Итог встречи «{title}» стоит в очереди к летописцу. Летописец сегодня — вы.",
  "🎬 Встреча «{title}» сыграна, не хватает только финальных титров.",
  "🧠 Память о встрече «{title}» тает быстрее мороженого. Запишите итог, пока помнится.",
  "⏳ «{title}» прошла, а в трекере у всех участников всё ещё висит «нужен итог». Пара слов — и её отпустят.",
];

export function recapNudgeText(title: string, who: string, seed: string): string {
  return `${pick(RECAP_NUDGES, seed).replace("{title}", title)}\n\n${who} просит подвести итог встречи.`;
}
